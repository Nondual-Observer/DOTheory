# Исследование 41, Этап 4. Скрипт 12: аналитическая формула для K без перебора
# K_n = #{неупорядоченные пары {a,b}: a≠b, a,b≠0, [P_a,P_b]=0, P_aP_b = −P_{a+b}}
# Формула: K_n = ((16^n + 4^n)/2 − 10^n)/4. Проверка перебором для n = 1..4.
# Вывод формулы: фаза произведения разлагается по кубитам; на кубите пара (p,q)
# даёт ±i, если p≠q оба неединичные (6 упорядоченных пар, знак ε_{pqr}), иначе 1
# (10 пар). Коммутируют ⇔ число «антикоммутирующих» позиций 2k чётно; фаза равна
# (−1)^k Π ε; ровно половина из 6^{2k} наборов знаков даёт −1. Отсюда упорядоченных
# пар Σ_{k≥1} C(n,2k)·6^{2k}/2·10^{n−2k} = ((16^n+4^n)/2 − 10^n)/2.
# =============================================================================
using LinearAlgebra
const X1 = ComplexF64[0 1; 1 0]; const Z1 = ComplexF64[1 0; 0 -1]
function Kbrute(n)
    NA = 4^n
    axv(a) = a & (2^n - 1); azv(a) = a >> n
    P(a) = im^(count_ones(axv(a) & azv(a)) % 4) * reduce(kron, [X1^((axv(a) >> (j - 1)) & 1) * Z1^((azv(a) >> (j - 1)) & 1) for j in 1:n])
    Ps = [P(a) for a in 0:NA-1]
    K = 0
    for a in 1:NA-1, b in a+1:NA-1
        A = Ps[a+1] * Ps[b+1]
        norm(A - Ps[b+1] * Ps[a+1]) < 1e-9 || continue
        real(tr(Ps[(a⊻b)+1]' * A)) < 0 && (K += 1)
    end
    K
end
Kformula(n) = ((big(16)^n + big(4)^n) ÷ 2 - big(10)^n) ÷ 4
for n in 1:4
    println("n = $n : перебор K = $(Kbrute(n)) ; формула K = $(Kformula(n))")
end
