#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_mass_gap_input.py — ИССЛЕДОВАНИЕ: вынуждает ли структура массовую щель,
или масса = вход (веса/связи на рёбрах)?

Контекст. Физ-функтор F: Q_n → спины даёт A_n = ∑_i σ_x^(i) (СВОБОДНЫЕ спины, без
взаимодействия). Голый куб вершинно-транзитивен ⟹ середина λ=0 вырождена ⟹ масс.щели
нет (безмассовый центр σ½). Вопрос: добавим минимальный ВХОД (веса w_i, затем
взаимодействие) — родится ли масса ВЫНУЖДЕННО, или вес/сила свободны? Заранее не
подгоняем: код сам покажет, что вынуждено (форма), а что свободно (значение).

  A. ГОЛЫЙ A=∑σ_x БЕЗМАССОВ: спектр {n−2k, крат. C(n,k)}; чётное n ⟹ λ=0 вырождено
     C(n,n/2) — нет щели в центре. Вершинно-транзитивно (S_n переставляет координаты).
  B. ВЕСА A_w=∑ w_i σ_x: спектр = {∑±w_i} (всё ещё СВОБОДНЫЕ моды). Несоизмеримые w
     уводят центр от 0 ⟹ щель Δ=min|∑±w_i|>0. НО Δ(2w)=2Δ(w) ⟹ масштаб (значение
     массы) НЕ вынужден — растяжимо.
  C. НЕТ выделенного w: S_n-симметрия голого куба ⟹ всякая перестановка w эквивалентна;
     структура не указывает привилегированный набор ⟹ ЗНАЧЕНИЕ свободно (вход).
  D. ВЫНУЖДЕНА ФОРМА (не значение): киральная Z=∏σ_z даёт {A_w,Z}=0 при ЛЮБЫХ w ⟹
     спектр СИММЕТРИЧЕН ±λ (частица/дырка). κ=∏σ_x КОММУТИРУЕТ при любых w (масса из
     этого слома НЕ родится — поперечное поле κ-инвариантно).
  E. НАСТОЯЩАЯ щель требует ВЗАИМОДЕЙСТВИЯ (член σ_z^(i)σ_z^(j), которого в голом кубе
     НЕТ): он расщепляет вырожденный центр и НАРУШАЕТ {·,Z}=0 (масса ломает частично-
     дырочную симметрию — как в реальности). Топология «кто с кем» может быть задана
     структурой (рёбра), СИЛА связи g — нет: Δ растёт с g ⟹ форма да, число нет.
  F. ОСЕВОЙ ДИПОЛЬ: слом ОДНОЙ оси (w_1≠остальные) уже снимает вырождение центра, и
     щель чувствительна ИМЕННО к сломанной оси (масса = осевое отклонение, не радиальное).

ВЫВОД проверяем, не постулируем. Если найдётся ВЫНУЖДЕННОЕ отношение весов — это мост
на 2-ю точку; если нет — стена подтверждена строго и локализована (= вершинная симметрия).
"""
from __future__ import annotations
import numpy as np
from math import comb
from itertools import product

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

I2 = np.eye(2)
SX = np.array([[0, 1], [1, 0]], dtype=float)
SZ = np.array([[1, 0], [0, -1]], dtype=float)

def op_at(P, i, n):
    """Оператор P на спине i, тождество на прочих (Кронекер)."""
    mats = [P if j == i else I2 for j in range(n)]
    out = mats[0]
    for m in mats[1:]:
        out = np.kron(out, m)
    return out

def transverse(weights):
    """A_w = ∑ w_i σ_x^(i)."""
    n = len(weights)
    H = np.zeros((1 << n, 1 << n))
    for i, w in enumerate(weights):
        H += w * op_at(SX, i, n)
    return H

def kron_all(P, n):
    out = P
    for _ in range(n - 1):
        out = np.kron(out, P)
    return out

def gap_around_zero(H):
    """Минимальный |λ| = щель вокруг нуля (масса безмассового центра)."""
    ev = np.linalg.eigvalsh(H)
    return float(np.min(np.abs(ev)))

def degeneracy_at_zero(H, tol=1e-9):
    ev = np.linalg.eigvalsh(H)
    return int(np.sum(np.abs(ev) < tol))


# ═══════ A. голый ∑σ_x безмассов (вырожденный центр) ═══════
def section_A():
    print("\n[A] ГОЛЫЙ A=∑σ_x БЕЗМАССОВ: середина λ=0 вырождена C(n,n/2), нет щели в центре")
    for n in (2, 4, 6):                                   # чётные: есть страт k=n/2
        H = transverse([1.0] * n)
        deg = degeneracy_at_zero(H)
        check(f"n={n}: λ=0 кратность {deg} = C({n},{n//2})={comb(n, n//2)} ⟹ безмассовый центр",
              deg == comb(n, n // 2))
    print("   → вершинно-транзитивно (все n осей равноправны): нет выделенной массы")


# ═══════ B. веса дают щель, но масштаб свободен ═══════
def section_B():
    print("\n[B] ВЕСА A_w=∑w_iσ_x: щель Δ=min|∑±w_i|>0, но Δ(2w)=2Δ(w) ⟹ значение НЕ вынуждено")
    w = [1.0, 1.3, 1.7, 2.1]                              # несоизмеримые
    Hd = transverse(w)
    gap1 = gap_around_zero(Hd)
    gap2 = gap_around_zero(transverse([2 * x for x in w]))
    # прямой счёт: щель = min по всем ±-комбинациям
    direct = min(abs(sum(s * x for s, x in zip(signs, w)))
                 for signs in product([1, -1], repeat=len(w)))
    check(f"несоизмеримые w: щель Δ={gap1:.4f}>0 (центр ушёл от нуля = масса появилась)",
          gap1 > 1e-6 and abs(gap1 - direct) < 1e-9)
    check(f"масштабирование: Δ(2w)={gap2:.4f} = 2·Δ(w)={2*gap1:.4f} ⟹ ВЕЛИЧИНА массы свободна (вход)",
          abs(gap2 - 2 * gap1) < 1e-9)


# ═══════ C. нет выделенного w (S_n-симметрия) ═══════
def section_C():
    print("\n[C] НЕТ привилегированного w: перестановка осей = автоморфизм ⟹ значение свободно")
    n = 4
    w = [1.0, 1.3, 1.7, 2.1]
    base = sorted(np.linalg.eigvalsh(transverse(w)))
    # любая перестановка весов даёт ТОТ ЖЕ спектр (координаты взаимозаменяемы)
    perms_equal = True
    for perm in [[1.3, 1.0, 2.1, 1.7], [2.1, 1.7, 1.3, 1.0], [1.7, 2.1, 1.0, 1.3]]:
        if not np.allclose(sorted(np.linalg.eigvalsh(transverse(perm))), base):
            perms_equal = False
    check("спектр инвариантен к перестановке весов ⟹ структура не выделяет набор w (значение=вход)",
          perms_equal)


# ═══════ D. вынуждена ФОРМА: ±λ симметрия и κ-инвариантность при любых w ═══════
def section_D():
    print("\n[D] ВЫНУЖДЕНА ФОРМА (не значение): {A_w,Z}=0 ⟹ спектр ±λ; [A_w,κ]=0 при ЛЮБЫХ w")
    for n in (2, 3, 4):
        w = [1.0 + 0.37 * i for i in range(n)]           # произвольные неравные
        A = transverse(w)
        Z = kron_all(SZ, n)                              # киральная κ
        X = kron_all(SX, n)                              # дополнение κ
        anti = A @ Z + Z @ A                             # {A,Z}
        comm = A @ X - X @ A                             # [A,κ]
        ev = np.linalg.eigvalsh(A)
        sym = np.allclose(sorted(ev), sorted(-ev))       # спектр ±λ
        check(f"n={n}: {{A_w,Z}}=0 (спектр ±λ симметричен: {sym}) И [A_w,κ]=0 — форма вынуждена",
              np.allclose(anti, 0) and np.allclose(comm, 0) and sym)
    print("   → частично-дырочная симметрия ±λ и κ-инвариантность держатся при любых весах (●форма)")


# ═══════ E. настоящая щель = ВЗАИМОДЕЙСТВИЕ (вход), сила свободна ═══════
def section_E():
    print("\n[E] НАСТОЯЩАЯ щель = взаимодействие σ_z⊗σ_z (НЕТ в голом кубе): сила g свободна")
    # минимальная модель: 2 спина, H = (σx⊗I + I⊗σx) + g·(σz⊗σz)
    Hx = op_at(SX, 0, 2) + op_at(SX, 1, 2)
    Hzz = op_at(SZ, 0, 2) @ op_at(SZ, 1, 2)
    base_gap = gap_around_zero(Hx)                        # g=0: вырожденный центр
    gaps = {}
    for g in (0.0, 0.5, 1.0, 2.0):
        gaps[g] = gap_around_zero(Hx + g * Hzz)
    grows = gaps[0.5] < gaps[1.0] < gaps[2.0]            # щель растёт с силой g
    Z = kron_all(SZ, 2)
    # взаимодействие НАРУШАЕТ {·,Z}=0? σzσz коммутирует с Z=σzσz (тривиально); берём σxσx как масс-член
    Hxx = op_at(SX, 0, 2) @ op_at(SX, 1, 2)
    anti_break = not np.allclose((Hx + Hxx) @ Z + Z @ (Hx + Hxx), 0)
    check(f"g=0 центр вырожден (щель={base_gap:.3f}); взаимодействие открывает щель и растёт с g "
          f"({gaps[0.5]:.3f}<{gaps[1.0]:.3f}<{gaps[2.0]:.3f})", base_gap < 1e-9 and grows)
    check("масс-член σx⊗σx НАРУШАЕТ {·,Z}=0 (масса ломает частично-дырочную симметрию, как в СМ)",
          anti_break)
    print("   → топология «кто с кем» может быть структурной (рёбра), но СИЛА g = ВХОД (значение)")


# ═══════ F. осевой диполь: слом ОДНОЙ оси снимает вырождение ═══════
def section_F():
    print("\n[F] ОСЕВОЙ ДИПОЛЬ: слом одной оси (w_1≠rest) снимает вырождение центра по ЭТОЙ оси")
    n = 4
    deg_sym = degeneracy_at_zero(transverse([1, 1, 1, 1]))       # симметрично: вырождено
    deg_broken = degeneracy_at_zero(transverse([1.6, 1, 1, 1]))  # слом оси 1
    # щель открылась именно от слома оси 1; величина = функция отклонения
    gap_small = gap_around_zero(transverse([1.2, 1, 1, 1]))
    gap_big = gap_around_zero(transverse([1.9, 1, 1, 1]))
    check(f"симметрично λ=0 крат.{deg_sym}; слом оси 1 ⟹ крат.{deg_broken} (вырождение снято)",
          deg_sym == comb(n, n // 2) and deg_broken < deg_sym)
    check(f"щель растёт с отклонением оси ({gap_small:.3f}→{gap_big:.3f}) — масса=ОСЕВОЕ отклонение",
          gap_big > gap_small > 0)
    print("   → масса = осевой диполь (слом κ по оси), НЕ радиальная мода")


def main():
    print("=" * 90)
    print("МАССА — ВЫНУЖДЕНА или ВХОД? Минимальный вход к свободным спинам, честный замер")
    print("=" * 90)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_F()
    print("\n" + "=" * 90)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: масса НЕ вынуждается голой структурой — вершинная транзитивность (все оси")
    print("       равноправны) есть САМА ПРИЧИНА безмассовости и невыводимости значения.")
    print("       ВЫНУЖДЕНА ФОРМА: щель есть/нет, ±λ-симметрия, осевой диполь, топология связей.")
    print("       СВОБОДНО ЗНАЧЕНИЕ: масштаб щели (сила g) — растяжим, структура его не выделяет.")
    print("       ⟹ мост на 2-ю точку ВОЗМОЖЕН ПО ФОРМЕ, но число массы = ВХОД. Стена [κ,Δ]=0")
    print("       не сломана; локализована точно: невыводимость массы = симметрия голого куба.")
    print("=" * 90)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
