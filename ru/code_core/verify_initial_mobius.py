#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_initial_mobius.py — две щели функторной машины (глава VIII), закрытые после сборки теории чисел.

Глава VIII §8.5 называет ТЕРМИНАЛЬНЫЙ объект (наблюдатель σ½), но не его двойственный — НАЧАЛЬНЫЙ.
И §8.6/IX даёт приведённую ацикличность Σ(−1)^k C(n,k)=0, но не отождествляет её с ФУНКЦИЕЙ МЁБИУСА
решётки = ОБРАЩЕНИЕМ (то, что в теории чисел стало 1/ζ=Σμ/nˢ). Здесь оба факта проверены строго (●).

Каждый check ФАЛЬСИФИЦИРУЕМ (рядом различающий контроль), без тавтологий.

  A. НАЧАЛЬНЫЙ ⊣ ТЕРМИНАЛЬНЫЙ (категория множеств-с-инволюцией κ, эквивариантные морфизмы):
     терминал {∗} (κ=id): |Hom(X,{∗})|=1 ∀X (§8.5, наблюдатель); начальный ∅: |Hom(∅,X)|=1 ∀X (семя).
     Оба ВНЕ лестницы Q_n (κ на Q_n свободно). Различающий: Q_n сам НЕ терминал (|End(Q_n)|>1) и НЕ
     начальный; из терминала в Q_n морфизмов НЕТ (нет κ-неподвижной точки) — он на верхнем конце.
  B. ФУНКЦИЯ МЁБИУСА = ОБРАЩЕНИЕ = приведённая ацикличность: μ(∅,S)=(−1)^|S|; Σ_k(−1)^k C(n,k)=0 (n≥1),
     =1 (n=0); обращение μ*ζ=δ (Σ_{T⊆S}μ(∅,T)=[S=∅]). Различающий: ζ без знаков (Σ_{T⊆S}1=2^|S|) НЕ
     обращает — знаки необходимы. Эйлерова хар-ка приведённого комплекса = Σμ по кубу.
"""
from __future__ import annotations
from itertools import product
from math import comb

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok


# объект = (носитель как кортеж, инволюция κ как dict); морфизм f эквивариантен: f(κx)=κ' f(x)
def Qn(n):
    N = 1 << n
    full = N - 1
    return (tuple(range(N)), {x: x ^ full for x in range(N)})       # κ = побитовое дополнение

TERM = ((0,), {0: 0})                                                # {∗}, κ=id (неподвижная точка)
INIT = ((), {})                                                      # ∅

def equivariant_homs(X, Y):
    (xs, kx), (ys, ky) = X, Y
    if not xs:
        return 1                                                     # из ∅ ровно один (пустое отображение)
    count = 0
    for assign in product(ys, repeat=len(xs)):
        f = dict(zip(xs, assign))
        if all(f[kx[x]] == ky[f[x]] for x in xs):                    # f(κx)=κ'f(x)
            count += 1
    return count


# ═══════ A. начальный ⊣ терминальный ═══════
def section_A():
    print("\n[A] НАЧАЛЬНЫЙ ∅ ⊣ ТЕРМИНАЛЬНЫЙ {∗}: 8.5 даёт только терминал; начальный (семя) — двойственный")
    objs = [INIT, Qn(1), Qn(2), Qn(3)]
    # терминал {∗}: из ЛЮБОГО объекта ровно один эквивариантный морфизм
    term_ok = all(equivariant_homs(X, TERM) == 1 for X in objs)
    # начальный ∅: в ЛЮБОЙ объект ровно один (пустое отображение)
    init_ok = all(equivariant_homs(INIT, X) == 1 for X in objs + [TERM])
    check("терминал {∗} (κ=id): |Hom(X,{∗})|=1 для всех X (§8.5 — наблюдатель σ½)", term_ok)
    check("★начальный ∅: |Hom(∅,X)|=1 для всех X — ДВОЙСТВЕННЫЙ объект (семя/фон), в 8.5 пропущен", init_ok)
    # различающий: Q_n сам НЕ терминал — у него >1 эндоморфизма (id и κ), и |Q_n|>1
    not_term = all(equivariant_homs(Qn(n), Qn(n)) > 1 for n in (1, 2, 3))
    check("различающий: Q_n НЕ терминал — |End(Q_n)|>1 (есть id и κ), |Q_n|=2ⁿ>1 ⟹ терминал ВНЕ лестницы",
          not_term)
    # терминал на ВЕРХНЕМ конце: из {∗} в Q_n морфизмов НЕТ (нужна κ-неподвижная точка, а κ свободно)
    no_down = all(equivariant_homs(TERM, Qn(n)) == 0 for n in (1, 2, 3))
    check("из терминала {∗} в Q_n морфизмов НЕТ (нет κ-неподвижной точки) ⟹ {∗}=верхний конец (σ½ вне сцены)",
          no_down)
    print("   → лестница: начальный ∅ (семя, нет различений) →…→ Q_n →…→ терминал {∗} (наблюдатель σ½);")
    print("     κ-двойственность стрелок меняет начальный↔терминальный (как 0↔∞ через инверсию в числах)")


# ═══════ B. функция Мёбиуса = обращение = ацикличность ═══════
def section_B():
    print("\n[B] ФУНКЦИЯ МЁБИУСА решётки = ОБРАЩЕНИЕ (μ*ζ=δ) = приведённая ацикличность Σ(−1)^k C(n,k)=0")
    mu = lambda S: (-1) ** bin(S).count("1")                         # μ(∅,S)=(−1)^|S| на булевой решётке
    # приведённая ацикличность = эйлерова хар-ка: Σ_k (−1)^k C(n,k) = (1−1)^n = 0 (n≥1), 1 (n=0)
    euler = {n: sum((-1) ** k * comb(n, k) for k in range(n + 1)) for n in range(7)}
    check("Σ_k(−1)^k C(n,k)=0 для n≥1 и =1 для n=0 (приведённая ацикличность комплекса = Σμ по кубу)",
          all(euler[n] == 0 for n in range(1, 7)) and euler[0] == 1)
    # обращение Мёбиуса μ*ζ=δ: Σ_{T⊆S} μ(∅,T) = [S=∅] (μ обратна ζ=константе 1 в алгебре инцидентности)
    inv = all(sum(mu(T) for T in range(1 << n) if (T & S) == T) == (1 if S == 0 else 0)
              for n in (1, 2, 3, 4) for S in range(1 << n))
    check("обращение μ*ζ=δ: Σ_{T⊆S}μ(∅,T)=[S=∅] ⟹ μ ОБРАЩАЕТ суммирование по решётке (в числах = 1/ζ=Σμ/nˢ)",
          inv)
    # различающий: ζ без знаков НЕ обращает — Σ_{T⊆S} 1 = 2^|S| ≠ δ (знакопеременность необходима)
    zeta_no_inv = all(sum(1 for T in range(1 << n) if (T & S) == T) == (1 << bin(S).count("1"))
                      for n in (1, 2, 3) for S in range(1 << n))
    check("различающий: ζ без знаков Σ_{T⊆S}1=2^|S| (НЕ δ) ⟹ знаки μ необходимы — обращение, не суммирование",
          zeta_no_inv)
    # связь с κ: μ(S)=(−1)^|S|, и μ(κS)=μ(∁S)=(−1)^{n−|S|}=(−1)^n·μ(S) — κ умножает Мёбиус на (−1)^n
    n = 4
    kappa_mu = all((-1) ** bin(((1 << n) - 1) ^ S).count("1") == (-1) ** n * mu(S) for S in range(1 << n))
    check("μ(κS)=(−1)ⁿ·μ(S): дополнение κ переводит знакопеременную сторону в себя с фактором (−1)ⁿ", kappa_mu)
    print("   → ацикличность (8.6/IX) = функция Мёбиуса решётки = ОБРАЩЕНИЕ; знакопеременная сторона машины,")
    print("     двойственная суммированию по рангам; в числах = μ Мёбиуса, 1/ζ=∏(1−p⁻ˢ)")


def main():
    print("=" * 96)
    print("ДВЕ ЩЕЛИ ФУНКТОРНОЙ МАШИНЫ (гл. VIII), закрытые сборкой теории чисел: начальный объект + Мёбиус")
    print("=" * 96)
    section_A(); section_B()
    print("\n" + "=" * 96)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД (●): (A) машина имеет НАЧАЛЬНЫЙ объект ∅ (семя/фон, |Hom(∅,X)|=1), двойственный терминалу")
    print("       {∗}=σ½ (наблюдатель); 8.5 называл только терминал — асимметрия закрыта. (B) приведённая")
    print("       ацикличность Σ(−1)^k=0 = ФУНКЦИЯ МЁБИУСА решётки = ОБРАЩЕНИЕ μ*ζ=δ (знакопеременная сторона,")
    print("       двойственная суммированию); в числах = μ, 1/ζ=Σμ/nˢ. Оба — закрытие щелей, не новые сущности.")
    print("=" * 96)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
