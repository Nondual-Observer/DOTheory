#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_growth_directions.py — оценка трёх направлений развития (А пучки, Б брейдинг,
В комонада). Честно: что доказуемо ●, что программа ○. Главное — В даёт РЕАЛЬНЫЙ результат.

А. ПУЧКИ на PG(n−1,2): лифт индуцирует образ; базовая функториальность ● ; полные
   когомологии пучков «различений» = программа ○ (нужно определить пучок).
Б. БРЕЙДИНГ: текущая моноидальная перестановка СИММЕТРИЧНА (c²=id); нетривиальный
   брейдинг (фазовый сдвиг) требует доп. фазовой структуры = ВХОД ○.
В. ★КОМОНАДА РОСТА: тройка Λ_L⊣π⊣Λ_R даёт не только монаду (π∘Λ=id), но и КОМОНАДУ
   G=Λ_L∘π (забыть координату = НАБЛЮДЕНИЕ/огрубление). КЛЮЧ: G ИДЕМПОТЕНТНА (G²=G,
   необратима = потеря информации) И [G,Δ]≠0 (НЕ коммутирует с лапласианом). Это и есть
   тот «второй оператор» — но он СТРЕЛА (необратимое наблюдение), не сигнатура. И он НЕ
   вход — он комонада уже имеющейся тройки сопряжённых.
"""
from __future__ import annotations
import numpy as np

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

def adjacency(n):
    N = 1 << n; A = np.zeros((N, N))
    for x in range(N):
        for i in range(n): A[x ^ (1 << i), x] = 1.0
    return A


# ═══════ А. пучки на PG: базовая функториальность лифта ═══════
def section_A():
    print("\n[А] ПУЧКИ на PG(n−1,2): лифт индуцирует образ (базовая функториальность ●)")
    # PG(n−1,2) = ненулевые 𝔽₂ⁿ; лифт PG(n−1,2)↪PG(n,2) вложением 𝔽₂ⁿ↪𝔽₂ⁿ⁺¹ (a↦a)
    for n in range(2, 6):
        pts_n = list(range(1, 1 << n))               # точки PG(n−1,2)
        lift = lambda a: a                            # вложение (старший бит 0)
        img = [lift(a) for a in pts_n]
        # лифт инъективен и точки попадают в PG(n,2) (ненулевые 𝔽₂ⁿ⁺¹)
        injective = len(set(img)) == len(pts_n)
        in_target = all(1 <= y < (1 << (n + 1)) for y in img)
        check(f"n={n}: лифт PG({n-1},2)↪PG({n},2) инъективен, образ в цели — индуцирует прямой образ",
              injective and in_target)
    print("   → база ● (лифт→образ); пучок «различений» и его когомологии = программа [○]")


# ═══════ Б. брейдинг: текущая перестановка симметрична ═══════
def section_B():
    print("\n[Б] БРЕЙДИНГ: текущая моноидальная перестановка СИММЕТРИЧНА (c²=id) — брейдинг=вход")
    # симметрия: c_{B,A}∘c_{A,B}=id, где c_{A,B}:Q_m□Q_n→Q_n□Q_m, (x,y)↦(y,x)
    for (m, n) in [(1, 1), (2, 1), (2, 2), (3, 2)]:
        Nm, Nn = 1 << m, 1 << n
        c_AB = np.zeros((Nn * Nm, Nm * Nn))           # (x,y)↦(y,x)
        for x in range(Nm):
            for y in range(Nn):
                c_AB[y * Nm + x, x * Nn + y] = 1.0
        c_BA = np.zeros((Nm * Nn, Nn * Nm))           # (y,x)↦(x,y)
        for y in range(Nn):
            for x in range(Nm):
                c_BA[x * Nn + y, y * Nm + x] = 1.0
        symm = np.allclose(c_BA @ c_AB, np.eye(Nm * Nn))   # c_{B,A}∘c_{A,B}=id
        check(f"m={m},n={n}: c_{{B,A}}∘c_{{A,B}}=id — перестановка СИММЕТРИЧНА, НЕ брейдинг", symm)
    print("   → нетривиальный брейдинг (c²≠id, фазовый сдвиг) требует фазовой структуры = ВХОД [○]")


# ═══════ В. ★КОМОНАДА РОСТА: второй оператор, не коммутирующий с Δ ═══════
def section_V():
    print("\n[В] ★КОМОНАДА G=Λ_L∘π (наблюдение): G²=G (необратима) И [G,Δ]≠0 — ВТОРОЙ ОПЕРАТОР")
    for n in range(2, 7):
        N = 1 << n
        top = 1 << (n - 1)                            # старшая координата
        # G = забыть старшую координату (Λ_L∘π): x ↦ x с обнулённым старшим битом
        G = np.zeros((N, N))
        for x in range(N):
            G[x & ~top, x] = 1.0                       # огрубление (pull-back наблюдения)
        D = n * np.eye(N) - adjacency(n)              # лапласиан
        # (1) КОМОНАДА: G²=G (идемпотент — необратимое огрубление/наблюдение)
        idemp = np.allclose(G @ G, G)
        # (2) НЕОБРАТИМА: ранг < N (потеря информации)
        rank = np.linalg.matrix_rank(G)
        irreversible = rank == N // 2
        # (3) ★НЕ КОММУТИРУЕТ с Δ: [G,Δ]≠0 (в отличие от κ!)
        non_comm = not np.allclose(G @ D - D @ G, 0)
        check(f"n={n}: G²=G (комонада, необратима, ранг={rank}=N/2) И [G,Δ]≠0 — второй оператор",
              idemp and irreversible and non_comm)
    print("   → комонада НАБЛЮДЕНИЯ (огрубление) НЕ коммутирует с Δ ⟹ необратимость = СТРЕЛА;")
    print("     это НЕ вход — комонада тройки Λ_L⊣π⊣Λ_R; κ обратим/статичен, комонада ломает")


# ═══════ синтез ═══════
def section_synth():
    print("\n[синтез] что даёт В для времени")
    print("   ● κ КОММУТИРУЕТ с Δ ([κ,Δ]=0) — обратимая статика (Уилер–ДеВитт);")
    print("   ● КОМОНАДА G наблюдения НЕ коммутирует ([G,Δ]≠0) и НЕОБРАТИМА (G²=G) — СТРЕЛА;")
    print("   ⟹ необратимость/стрела = огрубление (потеря информации), не κ; согласуется с");
    print("     Пейдж–Вуттерс (наблюдение=условие=комонада) и стрелой энтропии (огрубление);")
    print("   ○ НО это термодинамическая стрела (необратимость), ещё НЕ лоренцева СИГНАТУРА;")
    print("     сигнатура (−,+,+,+) по-прежнему отдельный вопрос. В даёт стрелу, не конус.")


def main():
    print("=" * 84)
    print("ТРИ НАПРАВЛЕНИЯ: А пучки (○ программа), Б брейдинг (○ вход), В комонада (● стрела)")
    print("=" * 84)
    section_A(); section_B(); section_V(); section_synth()
    print("\n" + "=" * 84)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: А, Б — осмысленные программы с честным входом/○. ★В ДАЁТ РЕЗУЛЬТАТ: комонада")
    print("       наблюдения G=Λ_L∘π необратима (G²=G) и [G,Δ]≠0 — второй оператор = СТРЕЛА")
    print("       (необратимое огрубление), из имеющейся тройки, не вход. Но не сигнатура.")
    print("=" * 84)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
