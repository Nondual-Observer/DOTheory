#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_zfc_in_tnr.py — ложится ли ZFC в ТНР?

ЧЕСТНЫЙ СТРУКТУРНЫЙ ОТВЕТ (проверяемая часть): ★ДИСКРЕТНАЯ сторона ТНР = ⋃Q_n с порядком ⊆, инволюцией κ и
БИТОВОЙ принадлежностью — это РОВНО наследственно-конечные множества V_ω под кодировкой Аккермана
(a∈b ⟺ бит a числа b установлен). V_ω ⊨ ZF−Infinity, причём ВЫБОР (AC) на конечном БЕСПЛАТЕН (теорема ZF).
⟹ ВСЕ аксиомы ZFC, КРОМЕ Бесконечности, ложатся в ТНР ТОЧНО (изоморфизм, не аналогия). Аксиома
БЕСКОНЕЧНОСТИ = РОВНО ШОВ |·|₂↔|·|∞: предел башни = МЕРА (гауссова изнанка),
не множество V_{ω+} ⟹ полный трансфинит ZFC НЕ выводится (вход ○). σ½ (κ-неподвижная точка) НЕТ ни в одном
кубе = РИФМА с классом Рассела (самодополнение вынесено ВНЕ универсума = наблюдатель/собственный класс).

Регистр: ● конечная теория множеств = дискретная ТНР (Аккерман, изоморфизм) · ◐ Inf=шов, σ½↔Рассел ·
○ трансфинит/AC-на-бесконечном = вход (та же стена значений).

  A. КОДИРОВКА АККЕРМАНА: a∈b ⟺ (b>>a)&1; куб Q_n={m:m<2ⁿ}=HF-множества над {0..n−1} (дискрет ТНР=V_ω).
  B. ОСНОВАНИЕ (Foundation) + НЕТ САМОПРИНАДЛЕЖНОСТИ: член строго меньше (a<n), ∈ фундирован, x∉x ∀x.
  C. ПАРА/ОБЪЕДИНЕНИЕ = решёточные операции куба (аксиомы Pairing/Union держатся поэлементно).
  D. СТЕПЕНЬ ≠ ЛИФТ: Power Set (n→2ⁿ ground) и лифт ТНР (n→n+1, ×2 точек) — РАЗНЫЕ операции роста, обе в HF.
  E. ВЫБОР на КОНЕЧНОМ = ТЕОРЕМА: конструктивная функция выбора (min) работает всегда ⟹ AC бесплатен.
  F. σ½ = класс Рассела: κ(x)=x НЕВОЗМОЖНО (Tr κ=0, κ²=id) ⟹ самодополнение ВНЕ куба (наблюдатель).
  G. БЕСКОНЕЧНОСТЬ = ШОВ: ранг каждого элемента КОНЕЧЕН, но НЕОГРАНИЧЕН ⟹ Inf=единств. аксиома вне машины.
  H. СТРАЖ ●◐○.
"""
from __future__ import annotations
from functools import reduce

PASS = 0; FAIL = 0
def check(name, cond):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}")
    PASS += ok; FAIL += (not ok)
    return ok

members = lambda n: [a for a in range(n.bit_length()) if (n >> a) & 1]   # Аккерман: члены множества-кода n


# ═══════════════ A. кодировка Аккермана = дискрет ТНР ═══════════════
def section_A():
    print("\n[A] КОДИРОВКА АККЕРМАНА: a∈b ⟺ (b>>a)&1; Q_n={m<2ⁿ}=HF над {0..n−1} (дискрет ТНР = V_ω)")
    # биекция ℕ↔HF: код восстанавливается из членов как Σ2^a (битовое представление — РЕАЛЬНАЯ обратимость)
    bij = all(sum(1 << a for a in members(n)) == n for n in range(256))
    check("ℕ↔HF биекция: n = Σ_{a∈n} 2^a (код ⟺ множество членов) для n<256 — принадлежность ЕСТЬ бит", bij)
    # куб Q_n = числа <2ⁿ = множества, все члены которых <n (ground {0..n−1})
    for n in (2, 3, 4):
        Qn = list(range(2 ** n))
        all_members_below = all(all(a < n for a in members(m)) for m in Qn)
        check(f"Q_{n}: {len(Qn)}=2^{n} точек, все члены <{n} (=подмножества ground {{0..{n-1}}}) ⟹ куб=фрагмент HF",
              len(Qn) == 2 ** n and all_members_below)


# ═══════════════ B. Foundation + нет самопринадлежности ═══════════════
def section_B():
    print("\n[B] ОСНОВАНИЕ (Foundation): член СТРОГО меньше (a<n) ⟹ ∈ фундирован, ∅=низ; x∉x ∀x")
    N = 512
    well_founded = all(all(a < n for a in members(n)) for n in range(1, N))   # каждый член строго меньше
    check(f"∀n∈[1,{N}): все члены a<n ⟹ ∈ фундирован (нет ∞-цепочек ∋), ∅=код0=единств. минимум", well_founded)
    no_self = all(not ((x >> x) & 1) for x in range(N))                       # бит x числа x НИКОГДА не стоит
    check(f"x∉x ∀x<{N} (бит x числа x = 0, ибо 2^x>x) ⟹ нет самопринадлежности (как Foundation в ZF)", no_self)
    # Рассел R={x:x∉x} = ВСЁ ⟹ не множество (собственный класс) — самопринадлежности нет НИ У КОГО
    check("⟹ класс Рассела R={x:x∉x} = весь универсум = НЕ элемент (собственный класс), как в ZF", no_self)


# ═══════════════ C. Pairing / Union = операции куба ═══════════════
def section_C():
    print("\n[C] ПАРА / ОБЪЕДИНЕНИЕ = решёточные операции куба (аксиомы держатся поэлементно)")
    pair = lambda a, b: (1 << a) | (1 << b)
    pairing_ok = all(set(members(pair(a, b))) == {a, b} for a in range(6) for b in range(6))
    check("Pairing: код {a,b}=(1<<a)|(1<<b), члены = ровно {a,b} (все a,b<6)", pairing_ok)
    # Union S = ⋃_{y∈S} y; код = OR членов; проверяем x∈⋃S ⟺ ∃y∈S: x∈y
    def union_code(S): return reduce(lambda u, y: u | y, members(S), 0)
    union_ok = True
    for S in range(128):
        uc = union_code(S)
        for x in range(8):
            lhs = bool((uc >> x) & 1)
            rhs = any((y >> x) & 1 for y in members(S))
            if lhs != rhs: union_ok = False
    check("Union: x∈⋃S ⟺ ∃y∈S(x∈y) для всех S<128, x<8 (код ⋃S = OR членов) — аксиома Объединения держится", union_ok)


# ═══════════════ D. Power Set ≠ лифт ═══════════════
def section_D():
    print("\n[D] СТЕПЕНЬ ≠ ЛИФТ: Power Set (ground n→2ⁿ) и лифт ТНР (n→n+1, точек ×2) — РАЗНЫЕ операции роста")
    # лифт ТНР: Q_n→Q_{n+1}, точек 2ⁿ→2^{n+1} (×2, +1 координата)
    lift_doubles = all(2 ** (n + 1) == 2 * 2 ** n for n in range(8))
    # Power Set: ground из n элементов → 2ⁿ подмножеств (новый ground = 2ⁿ); куб над ним = 2^(2ⁿ) точек
    power_explodes = all(2 ** (2 ** n) > 2 ** (n + 1) for n in range(2, 6))   # степень РАСТЁТ быстрее лифта
    check("лифт: точек 2ⁿ→2^{n+1} (×2, +1 ось) — генератор машины ТНР", lift_doubles)
    check("Power Set: ground n→2ⁿ ⟹ куб 2^(2ⁿ) ≫ лифт 2^{n+1} (n≥2) — ОБЕ операции в HF, машина итерирует ЛИФТ",
          power_explodes)


# ═══════════════ E. конечный выбор = теорема (AC бесплатен) ═══════════════
def section_E():
    print("\n[E] ВЫБОР на КОНЕЧНОМ = ТЕОРЕМА: конструктивная функция выбора (min) ⟹ AC бесплатен (вход лишь ∞)")
    # детерминированные непустые конечные семьи (без random): семья_k зависит от k структурно
    families = [
        [{1, 2}, {3}, {4, 5, 6}],
        [{i, i + 1} for i in range(1, 10)],
        [set(members(m)) for m in range(1, 20) if m],          # семьи из членов HF-кодов
        [{7}], [{2, 4, 8, 16}, {3, 9}],
    ]
    families = [F for F in families if all(len(s) for s in F)]   # все непустые
    choice = lambda F: [min(s) for s in F]                       # КОНСТРУКТИВНАЯ функция выбора
    ok = all(all(ch in s for ch, s in zip(choice(F), F)) for F in families) and \
         all(len(choice(F)) == len(F) for F in families)
    check("конечная семья непустых ⟹ функция выбора f(s)=min(s) ВСЕГДА существует и тотальна (без аксиомы) "
          "⟹ AC бесплатен на конечном; нетривиален ТОЛЬКО на бесконечной семье = вход ○", ok)


# ═══════════════ F. σ½ = класс Рассела (самодополнение вне куба) ═══════════════
def section_F():
    print("\n[F] σ½ = класс Рассела: κ(x)=x НЕВОЗМОЖНО (Tr κ=0, κ²=id) ⟹ самодополнение ВНЕ куба = наблюдатель")
    for n in (1, 2, 3, 4, 5):
        mask = (1 << n) - 1
        kappa = lambda x: x ^ mask
        involution = all(kappa(kappa(x)) == x for x in range(1 << n))
        fixed = [x for x in range(1 << n) if kappa(x) == x]
        check(f"Q_{n}: κ²=id={involution}, κ-неподвижных точек={len(fixed)}=0 (Tr κ=0) ⟹ σ½ НЕ точка куба "
              f"(самодополнение вынесено ВНЕ — как класс Рассела/наблюдатель)", involution and len(fixed) == 0)


# ═══════════════ G. Бесконечность = шов ═══════════════
def section_G():
    print("\n[G] БЕСКОНЕЧНОСТЬ = ШОВ |·|₂↔|·|∞: ранг КОНЕЧЕН у каждого, но НЕОГРАНИЧЕН ⟹ Inf вне машины")
    from functools import lru_cache
    import sys
    sys.setrecursionlimit(100000)
    @lru_cache(maxsize=None)
    def rank(n): return 0 if n == 0 else 1 + max(rank(a) for a in members(n))
    # башня a_0=0, a_{k+1}=2^{a_k}: ранг = k (каждый элемент конечного ранга)
    tower = [0]
    for _ in range(5):
        tower.append(1 << tower[-1])     # 0,1,2,4,16,65536
    ranks_ok = all(rank(tower[k]) == k for k in range(5))   # rank(65536)=4 и т.д.
    check(f"башня 0→1→2→4→16→65536: ранг = {[rank(tower[k]) for k in range(5)]} = 0..4 "
          f"(каждый элемент КОНЕЧНОГО ранга)", ranks_ok)
    # ранг неограничен: ∃ элемент любого конечного ранга, но НИ ОДИН не бесконечен ⟹ Inf = завершение башни
    unbounded = rank(tower[5]) == 5 and all(rank(n) < 10 ** 9 for n in range(64))
    check("ранг НЕОГРАНИЧЕН (∃ элемент ранга k ∀k), но ВСЕГДА конечен ⟹ Бесконечность (завершённое ⋃Q_n как "
          "ОБЪЕКТ) = единственная аксиома ВНЕ машины = ШОВ к |·|∞ (предел=мера, не V_{ω+}) ○", unbounded)


# ═══════════════ H. страж ═══════════════
def section_H():
    print("\n[H] СТРАЖ ●◐○")
    print("   ● дискрет ТНР = V_ω (Аккерман, изоморфизм): Extensionality/Foundation/Pairing/Union/Separation/")
    print("     Replacement держатся; AC БЕСПЛАТЕН на конечном (теорема ZF). Это РОВНО ZF−Infinity.")
    print("   ◐ Бесконечность = шов |·|₂↔|·|∞ (Inf=единств. аксиома вне машины); σ½ ↔ класс Рассела")
    print("     (самодополнение вне универсума); Power Set vs лифт = две операции роста.")
    print("   ○ полный ТРАНСФИНИТ ZFC (V_α, α≥ω; большие кардиналы) НЕ выводится: предел=мера (гауссова изнанка),")
    print("     не кумулятивная иерархия; AC-на-бесконечном НЕЗАВИСИМ (Гёдель/Коэн) = вход = та же стена значений.")


def main():
    print("=" * 100)
    print("ZFC в ТНР? — конечная часть ложится ТОЧНО (=V_ω, Аккерман); Бесконечность=шов; AC бесплатен/вход")
    print("=" * 100)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_F(); section_G(); section_H()
    print("\n" + "=" * 100)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: ZFC как ЦЕЛОЕ в ТНР НЕ «ложится». Точнее: ДИСКРЕТНАЯ сторона ТНР (⋃Q_n,⊆,κ,бит-∈) ЕСТЬ финитная")
    print("       теория множеств V_ω (Аккерман, ●) — туда ложатся ВСЕ аксиомы ZFC кроме Бесконечности, и выбор")
    print("       там БЕСПЛАТЕН. Аксиома Бесконечности = РОВНО шов к |·|∞ (предел=мера, не множество); полный")
    print("       трансфинит + AC-на-бесконечном = ВХОД (та же стена). σ½ = класс Рассела (самодополнение вне).")
    print("=" * 100)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
