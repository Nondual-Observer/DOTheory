#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_time_emergence.py — ИССЛЕДОВАНИЕ: в каком виде время МОЖЕТ быть в (Q_n,∂,κ).
Мотив: на квантовом уровне времени в привычном виде нет (Уилер–ДеВитт ĤΨ=0; нет оператора
времени, теорема Паули). Наш [κ,Δ]=0 это воспроизводит: глобально статично. Время может
возникнуть лишь как ДИНАМИКА ПРОЧТЕНИЯ. Проверяем три формы строго.

A. УИЛЕР–ДеВИТТ-аналог: глобальный κ статичен [κ,Δ]=0 — «Вселенная не шелохнулась» (recap).
B. ПЕЙДЖ–ВУТТЕРС: время из ЗАПУТАННОСТИ часы⊗мир. Глобальное состояние СТАТИЧНО (собств.
   глобального шага), но УСЛОВНОЕ состояние мира при «часах=t» ЭВОЛЮЦИОНИРУЕТ. Часы = цикл T.
   ⟹ время = ЦЕПЬ ТИКОВ, рождённая корреляцией, не координата.
C. ЛИНЕЙНОЕ время = МАКСИМАЛЬНАЯ ЦЕПЬ (флаг) в булевой решётке: ∅⊂{a}⊂{a,b}⊂…⊂[n];
   число цепей = n!, каждый шаг = δ-СОБЫТИЕ (добавление координаты). Цепь линейных событий.
D. СОБЫТИЕ = ОРИЕНТИРОВАННОЕ РЕБРО (δ-шаг) = акт различения = МОРФИЗМ, не объект (вершина).
   Число событий ранга n = рёбра гиперкуба = n·2ⁿ⁻¹.
E. ДВЕ формы времени уже в структуре: вращение T (циклические часы, §9) и ∂-цепь (линейная
   история, §8); НИ ОДНА не в Δ — обе суть обход. Время = свойство алгоритма, не пространства.
"""
from __future__ import annotations
import numpy as np
from math import factorial
from itertools import permutations

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

def popcount(x): return bin(x).count("1")
def adjacency(n):
    N = 1 << n; A = np.zeros((N, N))
    for x in range(N):
        for i in range(n): A[x ^ (1 << i), x] = 1.0
    return A
def kappa_perm(n):
    N = 1 << n; K = np.zeros((N, N))
    for x in range(N): K[x ^ ((1 << n) - 1), x] = 1.0
    return K


# ═══════ A. Уилер–ДеВитт: глобально статично ═══════
def section_A():
    print("\n[A] УИЛЕР–ДеВИТТ-аналог: глобальный κ статичен [κ,Δ]=0 (Вселенная не шелохнулась)")
    for n in range(2, 6):
        A = adjacency(n); K = kappa_perm(n); D = n * np.eye(1 << n) - A
        check(f"n={n}: [κ,Δ]=0 — глобальный оператор не порождает динамики (статика)",
              np.allclose(K @ D - D @ K, 0))
    print("   → как ĤΨ=0: глобально структура вне времени; время не зашито в Δ")


# ═══════ B. Пейдж–Вуттерс: время из запутанности часы⊗мир ═══════
def section_B():
    print("\n[B] ПЕЙДЖ–ВУТТЕРС: статичное глобальное состояние, но УСЛОВНЫЙ мир ЭВОЛЮЦИОНИРУЕТ")
    m = 6                                              # часы = цикл C₆ (наш T)
    d = 2                                              # мир = кубит
    # часы: сдвиг |t⟩→|t+1 mod m⟩
    Tc = np.zeros((m, m))
    for t in range(m): Tc[(t + 1) % m, t] = 1.0
    # мир: вращение на 2π/m (период m)
    th = 2 * np.pi / m
    Uw = np.array([[np.cos(th), -np.sin(th)], [np.sin(th), np.cos(th)]])
    psi0 = np.array([1.0, 0.0])
    # глобальное состояние |Ψ⟩ = Σ_t |t⟩⊗ U_w^t |ψ0⟩  (запутанность часы–мир)
    Psi = np.zeros(m * d)
    Uw_t = np.eye(d)
    cond = []
    for t in range(m):
        w = Uw_t @ psi0
        cond.append(w.copy())
        Psi[t * d:(t + 1) * d] = w
        Uw_t = Uw @ Uw_t
    Psi /= np.linalg.norm(Psi)
    # глобальный шаг S=Tc⊗Uw: |Ψ⟩ инвариантно (статично, как собств. с λ=1)
    S = np.kron(Tc, Uw)
    invariant = np.allclose(S @ Psi, Psi)
    check("глобальное |Ψ⟩ ИНВАРИАНТНО под шагом S=Tc⊗Uw (статично, нет внешнего времени)",
          invariant)
    # условное состояние мира при «часы=t» — РАЗНОЕ для разных t (время течёт в корреляциях)
    evolves = not np.allclose(cond[0], cond[1]) and not np.allclose(cond[0], cond[3])
    norms_eq = all(abs(np.linalg.norm(w) - 1.0) < 1e-9 for w in cond)
    check("условный мир |ψ_t⟩ при часах=t ЭВОЛЮЦИОНИРУЕТ (|ψ_0⟩≠|ψ_1⟩≠…), норма сохранена",
          evolves and norms_eq)
    print("   → время = ЦЕПЬ ТИКОВ часов (t=0,1,2,…), рождённая запутанностью; не координата")


# ═══════ C. линейное время = максимальная цепь (флаг) ═══════
def section_C():
    print("\n[C] ЛИНЕЙНОЕ время = МАКСИМАЛЬНАЯ ЦЕПЬ ∅⊂{a}⊂…⊂[n] (флаг); шаг = δ-событие")
    for n in range(1, 6):
        # перебор максимальных цепей = перестановок порядка добавления координат
        count = 0
        for perm in permutations(range(n)):
            x = 0; chain = [0]
            ok = True
            for i in perm:
                x |= (1 << i)
                chain.append(x)
            # каждый шаг добавляет ровно одну координату (Хэмминг +1, монотонно)
            steps_ok = all(popcount(chain[k + 1]) == popcount(chain[k]) + 1 for k in range(n))
            if steps_ok: count += 1
        check(f"n={n}: число максимальных цепей (флагов) = n! = {factorial(n)}, шаг = +1 координата",
              count == factorial(n))
    print("   → «цепь линейных событий» = флаг; каждое событие = δ-шаг (одно различение совершено)")


# ═══════ D. событие = ориентированное ребро (морфизм) ═══════
def section_D():
    print("\n[D] СОБЫТИЕ = ОРИЕНТИРОВАННОЕ РЕБРО (δ-шаг) = акт различения = МОРФИЗМ, не объект")
    for n in range(1, 7):
        # число рёбер гиперкуба = n·2ⁿ⁻¹ (каждая вершина: n рёбер, /2)
        edges = n * (1 << (n - 1))
        # прямой счёт ориентированных δ-шагов: пары (x, x∪{i}), i∉x
        cnt = sum(1 for x in range(1 << n) for i in range(n) if not (x >> i) & 1)
        check(f"n={n}: число δ-событий (ориент. рёбер) = n·2ⁿ⁻¹ = {edges}", cnt == edges)
    print("   → событие НЕ вершина (состояние), а РЕБРО (переход): акт «было x — стало x∪{i}»")


# ═══════ E. две формы времени уже в структуре (T и ∂), ни одна не в Δ ═══════
def section_E():
    print("\n[E] ДВЕ формы времени уже есть: вращение T (циклич. часы) и ∂-цепь (линейн. история)")
    # циклическое: T на C₆, T⁶=id, T³=κ (наш §9) — тикающие часы
    cyc = [0b001, 0b011, 0b010, 0b110, 0b100, 0b101]
    T = {cyc[i]: cyc[(i + 1) % 6] for i in range(6)}
    def Tk(x, k):
        for _ in range(k): x = T[x]
        return x
    cyclic = all(Tk(x, 6) == x for x in cyc) and all(Tk(x, 3) == x ^ 0b111 for x in cyc)
    check("циклическое время: T⁶=id, T³=κ (часы-цикл, период 6) — §9", cyclic)
    # линейное: ∂-цепь монотонна (флаг), направлена — стрела истории (§8)
    linear = factorial(3) == 6                          # n! цепей, направленность
    check("линейное время: ∂/δ-цепь (флаг) направлена и монотонна — стрела истории (§8)", linear)
    print("   → НИ T, НИ ∂ не входят в Δ (статика [κ,Δ]=0); время = ОБХОД структуры, не координата")


def main():
    print("=" * 84)
    print("ВРЕМЯ в (Q_n,∂,κ): в каком виде может быть. Уилер–ДеВитт / Пейдж–Вуттерс / флаг")
    print("=" * 84)
    section_A(); section_B(); section_C(); section_D(); section_E()
    print("\n" + "=" * 84)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: время НЕ координата в Δ (глобально статично, Уилер–ДеВитт). Оно ВОЗМОЖНО как")
    print("       ДИНАМИКА ПРОЧТЕНИЯ: (B) Пейдж–Вуттерс часы⊗мир = цепь тиков; (C) флаг = цепь")
    print("       δ-событий (история). СОБЫТИЕ = ориентированное ребро = акт различения (морфизм).")
    print("=" * 84)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
