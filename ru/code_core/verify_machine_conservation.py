    print("       (спуск внутрь), сшитых звездой Ходжа κ∂=δκ; их БАЛАНС = приведённая Эйлерова Σ(−1)ᵏC(n,k)=0 =")
    print("       СОБСТВЕННЫЙ аддитивный ∏=1 машины (что выросло наружу = что пришло внутрь), двусторонний вокруг")
