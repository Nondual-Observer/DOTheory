#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_continuum_limit.py — ЧЕСТНАЯ проверка предложения «непрерывность = спектральный
предел Q_n», а не выдача схемы за построение.

Предложение: Q_n → лапласиан Δ_n → спектр → масштабный предел → (M,g) → σ½=KMS-фикс.
Метод верен (спектральная геометрия — реальный механизм дискрет→континуум; κ→звезда Ходжа
у нас УЖЕ доказана). Вопрос: что предел даёт НА ГИПЕРКУБЕ — многообразие или меру?

ПРОВЕРЯЕМ:
A. скалярный лапласиан гиперкуба L=D−A=nI−A; спектр {2k, кратность C(n,k)} (над ℝ, канонично).
B. тепловой след Z(t)=Tr e^{−tL}=(1+e^{−2t})ⁿ — точная формула.
C. СПЕКТРАЛЬНАЯ РАЗМЕРНОСТЬ d_s(t)=−2 dlnZ/dlnt НЕ постоянна (нет плато) ⟹ предел НЕ
   d-многообразие: гиперкуб спектрально не геометричен в смысле (M,g).
D. распределение собственных значений → ГАУССИАН (ЦПТ) ⟹ предел = МЕРА (наша изнанка-вес),
   не метрика. Это согласуется с корпусом (непрерывная сторона = мера), но не даёт (M,g).
E. честный вывод: κ→Ходж реально [◐]; предел=мера [●]; (M,g)/размерность/сигнатура=ВХОД [○].

⚠ Над 𝔽₂ ∂²=0, но СПЕКТРА нет; над ℝ скалярный L=D−A каноничен (знаки не нужны), но полный
   Ходж-комплекс над ℝ требует ОРИЕНТАЦИЙ (знаков) — доп. структура (мягкий вход).
"""
from __future__ import annotations
import numpy as np
from math import comb, exp, log

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

def adjacency(n):
    N = 1 << n; A = np.zeros((N, N))
    for x in range(N):
        for i in range(n): A[x ^ (1 << i), x] = 1.0
    return A


# ═══════ A. спектр скалярного лапласиана гиперкуба ═══════
def section_A():
    print("\n[A] лапласиан гиперкуба L=nI−A: спектр {2k, кратность C(n,k)} (канонично над ℝ)")
    from collections import Counter
    for n in range(1, 8):
        A = adjacency(n)
        L = n * np.eye(1 << n) - A
        ev = np.round(np.linalg.eigvalsh(L)).astype(int)
        got = Counter(ev.tolist())
        want = Counter({2 * k: comb(n, k) for k in range(n + 1)})
        check(f"n={n}: spec(L) = {{2k : k=0..{n}}} с кратностями C(n,k)", got == want)


# ═══════ B. тепловой след Z(t)=(1+e^{−2t})ⁿ ═══════
def section_B():
    print("\n[B] тепловой след Z(t)=Tr e^{−tL} = (1+e^{−2t})ⁿ (точно)")
    for n in (3, 5, 7):
        for t in (0.05, 0.2, 0.5, 1.0):
            Z_direct = sum(comb(n, k) * exp(-2 * t * k) for k in range(n + 1))
            Z_formula = (1 + exp(-2 * t)) ** n
            check(f"n={n}, t={t}: Z(t)=(1+e^{{−2t}})ⁿ", abs(Z_direct - Z_formula) < 1e-9)


# ═══════ C. спектральная размерность НЕ постоянна (нет многообразия) ═══════
def section_C():
    print("\n[C] спектральная размерность d_s(t)=−2 dlnZ/dlnt — НЕТ ПЛАТО ⟹ предел НЕ d-многообразие")
    # d_s(t) = 4 n t e^{−2t} / (1+e^{−2t})   (аналитически из Z=(1+e^{−2t})ⁿ)
    def d_s(n, t):
        return 4 * n * t * exp(-2 * t) / (1 + exp(-2 * t))
    for n in (10, 20, 50):
        # для d-многообразия d_s(t)≈const на окне малых t; у гиперкуба — меняется в разы
        window = [0.005, 0.01, 0.02, 0.05, 0.1]
        vals = [d_s(n, t) for t in window]
        ratio = max(vals) / max(min(vals), 1e-9)
        check(f"n={n}: d_s(t) меняется в {ratio:.0f}× на окне малых t (нет плато ⟹ не многообразие)",
              ratio > 5)
        # при t→0 d_s→0 (точечно-подобно/мерно), не фиксированная размерность
        check(f"n={n}: d_s(t→0)→0 (предел мерный, не d-мерный): d_s(0.001)={d_s(n,0.001):.3f}",
              d_s(n, 0.001) < 0.5)


# ═══════ D. распределение собственных значений → гауссиан (предел = МЕРА) ═══════
def section_D():
    print("\n[D] распределение спектра → ГАУССИАН (ЦПТ) ⟹ предел = МЕРА (изнанка-вес), не метрика")
    # собственные значения 2k, k~Binomial(n,1/2); (k−n/2)/√(n/4) → N(0,1)
    def ks_to_normal(n):
        # эмпирическая CDF нормированных уровней vs стандартный нормальный
        from math import erf, sqrt
        ks = sorted(range(n + 1))
        weights = [comb(n, k) for k in ks]
        tot = sum(weights)
        mu, sd = n / 2, sqrt(n / 4)
        cum = 0.0; D = 0.0
        for k, w in zip(ks, weights):
            cum += w / tot
            z = (k - mu) / sd
            Phi = 0.5 * (1 + erf(z / sqrt(2)))
            D = max(D, abs(cum - Phi))
        return D
    prev = 1.0
    for n in (10, 50, 200, 800):
        D = ks_to_normal(n)
        check(f"n={n}: KS-расстояние спектра до N(0,1) = {D:.4f} (↓ ⟹ предел=гауссова мера)",
              D < prev)
        prev = D
    print("   → масштабный предел спектра = гауссова мера на ℝ¹ (= вес/изнанка корпуса), НЕ (M,g)")


# ═══════ E. честный итог ═══════
def section_E():
    print("\n[E] ЧЕСТНЫЙ ИТОГ по предложению")
    print("   ● метод верен: непрерывность как СПЕКТРАЛЬНЫЙ ПРЕДЕЛ (не отождествление) — лучше;")
    print("   ● κ→звезда Ходжа УЖЕ доказана дискретно (один оператор: κ∂=δκ);")
    print("   ● на гиперкубе предел = ГАУССОВА МЕРА (изнанка-вес), спектр.размерность нестабильна;")
    print("   ○ (M,g): риманова метрика/размерность НЕ выводятся — нужен иной дискрет (триангуляция")
    print("     многообразия) или мера/масштаб = ВХОД; на голом Q_n их нет;")
    print("   ○ Lorentzian (+,−,−,−): κ-спектр СИММЕТРИЧЕН (±λ), сигнатура не выводится; Wick=вход;")
    print("   ○ конвергенция к (M,g) и связь с динамикой ОТО — не доказаны (автор предложения признаёт).")
    print("   ⟹ предложение даёт СТЕНЕ спектральную форму (предел=мера=изнанка), НЕ пробивает её.")


def main():
    print("=" * 84)
    print("ОЦЕНКА ПРЕДЛОЖЕНИЯ «непрерывность = спектральный предел Q_n» — что РЕАЛЬНО даёт")
    print("=" * 84)
    section_A(); section_B(); section_C(); section_D(); section_E()
    print("\n" + "=" * 84)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: метод верен (спектр.предел), κ=Ходж уже наша; НО предел гиперкуба = ГАУССОВА")
    print("       МЕРА (изнанка), НЕ (M,g). Метрика/размерность/сигнатура = ВХОД [○]. Стена та же,")
    print("       теперь спектральная: предложение даёт ей форму, не пробивает.")
    print("=" * 84)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
