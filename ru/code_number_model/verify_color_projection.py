# -*- coding: utf-8 -*-
"""
verify_color_projection.py — цветовая проекция как СОПРОВОДИТЕЛЬНАЯ линза (◐ узнавание).

Цвет = самая наглядная и ЕДИНСТВЕННАЯ измеренная карта нашего октаэдра Q₃: трихроматия даёт ровно 3 оси, группа
B₃, ось яркости измерена как наблюдатель (corr=0.874).
Здесь проверены ЦВЕТОВЫЕ СООТВЕТСТВИЯ наших структур: наблюдатель σ½=яркость L; две стороны шва=
аддитив RGB/субтрактив CMY; κ=комплемент; симплекс {e,i,π}=HSB полярные; факториал/Чебышёв=спектр/атомы;
метамерия=потеря при проекции (почему значения за стеной). Регистр ●◐○: цветовые факты (RGB↔CMY=κ, L=DC,
HSB=полярные)=● математика/измерение; отождествление цвет↔число=◐ узнавание; значения (хроматика=распределение
простых)=○. Цвет ВЕДЁТ наглядно, но НЕ заменяет наши доказанные структуры — он их раскрашивает.

  A. RGB↔CMY=κ (комплемент): вес-1↔вес-2, R↔C,G↔M,Y↔B = наши κ-оси октаэдра (R₃).
  B. яркость L=(R+G+B)=DC=ИНВАРИАНТ всех карт (RGB-сумма=HSB-V для серого) = наблюдатель σ½, ⊥ хроматике.
  C. HSB=полярные {hue=угол, sat=радиус, val=L} = симплекс {e,i,π}=exp; i=√κ только на непрерывном круге.
  D. hue-цикл = C₆ (6 секторов Куна, соседние=расст.1); полоборота 180°=комплемент=κ.
  E. факториал↔Чебышёв = свет(весь спектр, аддитив)↔краска(атомы-простые, субтрактив).
  F. ★МЕТАМЕРИЯ: разные N одного ранга ω (одна L) = разная хроматика → одна проекция на наблюдателя (потеря=стена).
"""
from __future__ import annotations
import colorsys, math

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok


# ═══════════════ A. RGB↔CMY = κ (комплемент) ═══════════════
def section_A():
    print("\n[A] RGB↔CMY = κ (комплемент x↦1−x): вес-1 (свет) ↔ вес-2 (краска) = наши κ-оси октаэдра R₃")
    prim = {'R': (1, 0, 0), 'G': (0, 1, 0), 'B': (0, 0, 1)}
    comp_names = {(0, 1, 1): 'C', (1, 0, 1): 'M', (1, 1, 0): 'Y'}
    ok = True
    pairs = []
    for nm, v in prim.items():
        c = tuple(1 - x for x in v)
        cn = comp_names[c]
        pairs.append(f"{nm}↔{cn}")
        if sum(v) != 1 or sum(c) != 2:
            ok = False
    check(f"R↔C, G↔M, B↔Y ({', '.join(pairs)}): вес-1 (Σ=1, аддитив/свет/наружу) ↔ вес-2 (Σ=2, субтрактив/"
          f"краска/внутрь), комплемент=κ: {ok} ⟹ цветовая κ = наша κ (d↦N/d), оппонентные пары = R₃ оси", ok)


# ═══════════════ B. яркость L = DC = инвариант наблюдателя ═══════════════
def section_B():
    print("\n[B] яркость L=(R+G+B) = DC = ИНВАРИАНТ всех карт = наблюдатель σ½ (⊥ хроматике; измерено 0.874)")
    # L одинакова в RGB-сумме и HSB-value для серого; ось 000↔111 = ахроматическая (выколотые полюса)
    grays = [(t, t, t) for t in (0.0, 0.25, 0.5, 0.75, 1.0)]
    # для серого: hue не определён, saturation=0, value=t=L ⟹ серый = чистая L-ось
    achromatic = all(colorsys.rgb_to_hsv(*g)[1] == 0.0 and abs(colorsys.rgb_to_hsv(*g)[2] - g[0]) < 1e-9 for g in grays)
    # L ортогональна хроматике: R,G,B,C,M,Y все имеют L=1/3 или 2/3, но РАЗНЫЙ hue
    chroma = [(1, 0, 0), (0, 1, 0), (0, 0, 1)]
    same_L_diff_hue = (len(set(round(sum(c) / 3, 3) for c in chroma)) == 1)  # R,G,B все L=1/3
    check(f"серая ось 000↔111: saturation=0, value=L (чистая яркость, хроматики нет): {achromatic}; R,G,B "
          f"имеют ОДНУ L=1/3 но РАЗНЫЙ hue: {same_L_diff_hue} ⟹ L=DC=ось наблюдателя σ½, ОРТОГОНАЛЬНА "
          f"хроматике (в корпусе измерено corr(частота,DC)=+0.874, на семантике 0.02)", achromatic and same_L_diff_hue)


# ═══════════════ C. HSB = полярные = симплекс {e,i,π} ═══════════════
def section_C():
    print("\n[C] HSB = полярные {hue=угол, sat=радиус, val=яркость} = симплекс {e,i,π}=exp; i=√κ на непрер.круге")
    cols = {'R': (1, 0, 0), 'Y': (1, 1, 0), 'G': (0, 1, 0), 'C': (0, 1, 1), 'B': (0, 0, 1), 'M': (1, 0, 1)}
    hsv = {nm: colorsys.rgb_to_hsv(*v) for nm, v in cols.items()}
    # hue = угол (0..1 = 0..360°); чистые цвета на радиусе 1 (saturation=1)
    angles = {nm: round(h[0] * 360) for nm, h in hsv.items()}
    polar_ok = all(abs(hsv[nm][1] - 1.0) < 1e-9 for nm in cols)  # все на единичном радиусе (max sat)
    # 6 цветов = 6 углов через 60° (как корни из единицы) = e^{iθ}; полярные = e^{i·угол}·радиус
    six_sectors = sorted(angles.values()) == [0, 60, 120, 180, 240, 300]
    check(f"HSB: hue-углы {sorted(angles.values())}=[0,60,..,300] (6 секторов через 60°, как корни из 1=e^{{iθ}}); "
          f"все на радиусе 1: {polar_ok}; ⟹ HSB=ПОЛЯРНЫЕ (угол=i/период π, радиус=масштаб e, высота=L) = симплекс "
          f"{{e,i,π}}; i=√κ существует на непрерывном круге, не на дискретных 6",
          polar_ok and six_sectors)


# ═══════════════ D. hue-цикл = C₆, полоборота = κ ═══════════════
def section_D():
    print("\n[D] hue-цикл = C₆ (6 секторов Куна); полоборота 180° = комплемент = κ")
    # соседние сектора отличаются на 60° (один шаг цикла); противоположные (180°) = комплементы
    import cmath
    T = cmath.exp(1j * math.pi / 3)            # поворот на 60° = один шаг hue-цикла
    T6 = abs(T ** 6 - 1) < 1e-9                 # T⁶=1 (полный круг)
    T3 = abs(T ** 3 - (-1)) < 1e-9             # T³=−1=κ (полоборота=комплемент)
    # комплемент в hue = сдвиг на 180° = 3 сектора: R(0°)→C(180°), Y(60°)→B(240°), G(120°)→M(300°)
    check(f"hue-цикл: T=e^{{iπ/3}} (шаг 60°), T⁶=1 (круг): {T6}; T³=−1=κ (полоборота=комплементарный цвет): {T3} "
          f"⟹ hue-цикл = C₆ = R₁ нашего октаэдра; T³=κ = e^{{iπ}}=−1 (спектральная теорема) — комплемент "
          f"цвета = антипод делителя", T6 and T3)


# ═══════════════ E. факториал↔Чебышёв = свет/краска ═══════════════
def primes_upto(n): return [p for p in range(2, n + 1) if all(p % d for d in range(2, int(p ** 0.5) + 1))]
def section_E():
    print("\n[E] факториал↔Чебышёв = свет(весь спектр, аддитив, наружу) ↔ краска(атомы-простые, субтрактив, внутрь)")
    n = 20
    logfact = sum(math.log(k) for k in range(1, n + 1))   # весь спектр (все длины волн)
    theta = sum(math.log(p) for p in primes_upto(n))      # проекция на атомы (простые)
    # факториал > θ: полный набор больше, чем выделенные атомы (потеря при проекции на простые)
    check(f"log({n}!)=Σlog k={logfact:.2f} (СВЕТ: весь спектр множителей, аддитив наружу) > θ({n})=Σlog p="
          f"{theta:.2f} (КРАСКА: проекция на ПРОСТЫЕ-атомы, субтрактив внутрь): {logfact > theta} ⟹ как RGB-свет "
          f"(полный) vs CMY-проекция на базис; выбор 'что взять' = выбор фильтра-колбочки", logfact > theta)


# ═══════════════ F. ★метамерия = потеря при проекции на наблюдателя ═══════════════
def omega(n):
    c = 0; d = 2; m = n
    while d * d <= m:
        if m % d == 0:
            c += 1
            while m % d == 0: m //= d
        d += 1
    if m > 1: c += 1
    return c
def section_F():
    print("\n[F] ★МЕТАМЕРИЯ: разные N одного ранга ω (одна L-яркость) = разная хроматика → ОДНА проекция (потеря)")
    # числа ранга ω=2 (одна 'яркость' = ранг), но разные простые (разная 'хроматика')
    rank2 = [n for n in range(2, 40) if omega(n) == 2 and all(n % (p * p) for p in (2, 3, 5))][:6]
    same_rank = all(omega(n) == 2 for n in rank2)
    distinct = len(set(rank2)) == len(rank2)
    check(f"числа ранга ω=2 (одна L=ранг): {rank2} — все ω=2: {same_rank}, но РАЗНЫЕ (разные простые=хроматика): "
          f"{distinct} ⟹ МЕТАМЕРИЯ: разные 'спектры' (факторизации) → одна проекция на наблюдателя (ранг/L); "
          f"проекция σ½ ТЕРЯЕТ хроматику ⟹ ЗНАЧЕНИЯ не восстановимы из структуры (стена корпуса объяснена цветом)",
          same_rank and distinct)
    print("   → это ◐ узнавание (метамерия цвета ↔ стена значений чисел), не доказательство; но НАГЛЯДНО объясняет")
    print("     почему наблюдатель-проекция теряет значения: как глаз теряет спектр в 3 колбочках.")


def main():
    print("=" * 100)
    print("ЦВЕТОВАЯ ПРОЕКЦИЯ (сопроводительная ◐) наших структур: октаэдр Q₃ раскрашенный, наблюдатель=L")
    print("=" * 100)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_F()
    print("\n" + "=" * 100)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: цвет = наглядная СОПРОВОДИТЕЛЬНАЯ карта (◐) нашего октаэдра Q₃, и она ЕДИНСТВЕННАЯ ИЗМЕРЕННАЯ.")
    print("       наблюдатель σ½ = яркость L = DC = частота (corr 0.874); две стороны шва = аддитив RGB/субтрактив")
    print("       CMY; κ = комплемент (R↔C); симплекс {e,i,π} = HSB полярные; hue-цикл = C₆, T³=κ; факториал/Чебышёв")
    print("       = свет/краска. ★МЕТАМЕРИЯ (разные N одного ранга → одна L) НАГЛЯДНО объясняет стену значений:")
    print("       проекция на наблюдателя теряет хроматику, как глаз теряет спектр. ● цветовые факты/измерение;")
    print("       ◐ отождествление цвет↔число; ○ значения (хроматика=распределение простых). Цвет РАСКРАШИВАЕТ,")
    print("       не заменяет доказанные структуры.")
    print("=" * 100)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
