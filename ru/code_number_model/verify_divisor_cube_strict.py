"""
verify_divisor_cube_strict.py — СТРОГОЕ математическое ядро: решётка делителей = куб; проекция на ранги.

ЧИСТАЯ математика — все утверждения ● (теоремы элементарной теории чисел, проверенные вычислением);
НИКАКОЙ физической оптики. Каждый check ФАЛЬСИФИЦИРУЕМ — рядом различающий контроль; ничего не вписано
руками как «ответ себе».

  A. СТРУКТУРНАЯ ТЕОРЕМА: D(N) ≅ ∏ᵢ Cℓ(aᵢ+1) (произведение цепей). Делитель ↔ вектор показателей
     (e₁,…,e_k), 0≤eᵢ≤aᵢ; делимость ⟺ покоординатное ≤. Решётка делителей = «коробка».
  B. БЕСКВАДРАТНОЕ ⟺ БУЛЕВ КУБ: N squarefree ⟺ D(N) ≅ Q_k (все цепи длины 2). Делитель ↔ битовый вектор,
     делимость ⟺ ⊆. Различающий: N=12=2²·3 — не куб (|D|=6≠2^k).
  C. ЧИСЛО ДЕЛИТЕЛЕЙ: d(N)=∏(aᵢ+1) (= |решётки|); для squarefree d(N)=2^ω(N)=|Q_k|.
  D. МЁБИУС = ЗНАК ВЕРШИНЫ + ВКЛ-ИСКЛ: μ(N)=(−1)^ω на squarefree, 0 на квадратах; Σ_{d|N} μ(d)=[N=1]
     (=(1−1)^k на кубе = включение-исключение). Различающий: для N>1 сумма НУЛЬ, для N=1 — единица.
  E. САМОДВОЙСТВЕННОСТЬ: d↦N/d — биекция делителей, ОБРАЩАЮЩАЯ делимость (антиизоморфизм решётки); на
     squarefree это κ:x↦1−x (битовое дополнение, антипод куба).
  F. ПРОЕКЦИЯ НА РАНГИ: rank(N):=ω(N) (число РАЗЛИЧНЫХ простых) = размерность куба-носителя Q_{ω(N)};
     уровни куба делителей squarefree = биномиальные C(k,j) (вес = число простых множителей делителя).
  G. ЛОКАЛЬНОСТЬ (Эйлер): σ(N)=∏_p (1+p+…+p^a) — мультипликативна, локальный множитель = сумма по этажам
     одной оси. Различающий: σ мультипликативна на взаимно простых, НЕ аддитивна.

  ── АТЛАС ОПЕРАЦИЙ (0 NOT 1 + × ^ ! ∞) — куда ложится каждое действие ──
  H. БУЛЕВА АЛГЕБРА: D(бесквадратного N) = булева алгебра (⊥=1, ⊤=N, ∧=gcd, ∨=lcm, ¬=N/d); дополнение
     d∧¬d=1, d∨¬d=N; де Морган. Сюда ложатся 1 (низ), NOT (¬), ∧/∨. Различающий: 12 не булева.
  I. УМНОЖЕНИЕ = СКЛЕЙКА ОСЕЙ: × взаимно простых = Q_a × Q_b = Q_(a+b) (декартово произв., ранг +).
     Различающий: НЕ coprime — ранг не складывается.
  J. ФАКТОРИАЛ = ОБХОДЫ КУБА: n! → k! = число максимальных цепей куба Q_k (все пути ⊥→⊤). n! не
     бесквадратно (Лежандр v_p(n!)=Σ⌊n/pⁱ⌋) — живёт высоко над кубом.
  K. МЁБИУС → ∞: μ слеп к этажам (≠0 ⟺ вершина куба); μ*1=δ (обратный к 1 в кольце Дирихле); 1/ζ=Σμ/nˢ=
     ∏(1−p⁻ˢ) — μ ОБРАЩАЕТ Эйлерово произведение; предел s→1: ζ→∞ (полюс), 1/ζ→0 ⟹ μ у ∞-полюса.
  L. ПОЛЮСА 0 и ∞: 0 = нижнее отсечение (нейтрал +, поглотитель ×, вне куба = фон); 0→1 = первое
     различение (аддит. инвариант); κ:d↦N/d меняет полюса (1↔N), центр √N=σ½; ∞ = ранг неограничен.

  ── ВТОРАЯ РЕАЛИЗАЦИЯ (вычеты) + ФУНКТОРНЫЙ СЛОВАРЬ ──
  M. ЕВКЛИД + БЕЗУ: gcd через остатки (=∧ решётки); gcd(a,b)=ax+by (конструктивный инфимум).
  N. КТО: ℤ/n ≅ ∏ ℤ/pᵢ^aᵢ — кольцевой изоморфизм = моноидальность □ на ВЫЧЕТАХ (2-я реализация куба).
  O. φ ЭЙЛЕРА: мультипликативна (=□); φ(p^a)=p^a−p^(a−1); Σ_{d|n}φ(d)=n (φ*1=Id); φ=μ*Id (вкл-искл).
  P. v_p НОРМИРОВАНИЕ = высота этажа: v_p(mn)=v_p(m)+v_p(n) (×→+); |n|_p=p^(−v_p); ∏|n|_v=1 (мост к |·|∞).
  Q. ФЕРМА/ЭЙЛЕР: a^φ(n)≡1 (mod n); (ℤ/n)* группа порядка φ(n); для простого циклична (первообр. корень).
  R. ФУНКТОРНЫЙ СЛОВАРЬ: Λ:S↦∏p — функтор (сохраняет порядок ⊆↦|, моноидальность □↦×, κ↦d↦N/d);
     на бесквадратных = ИЗОМОРФИЗМ категорий, функторы машины реализованы СТРОГО (●), не узнаны (◐ лишь σ½).
"""
from __future__ import annotations
from itertools import product
from math import prod, comb, gcd, pi, factorial

def lcm(a, b):
    return a * b // gcd(a, b)

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

def factorize(n):
    f, d = {}, 2
    while d * d <= n:
        while n % d == 0:
            f[d] = f.get(d, 0) + 1; n //= d
        d += 1
    if n > 1: f[n] = f.get(n, 0) + 1
    return f

def divisors(n):
    return sorted(d for d in range(1, n + 1) if n % d == 0)

def omega(n):           # число РАЗЛИЧНЫХ простых
    return len(factorize(n))

def mobius(n):
    f = factorize(n)
    return 0 if any(a >= 2 for a in f.values()) else (-1) ** len(f)

def phi(n):             # тотиент Эйлера = |(ℤ/nℤ)*|
    return sum(1 for k in range(1, n + 1) if gcd(k, n) == 1)

def vp(n, p):           # p-адическое нормирование = высота этажа по оси p
    v = 0
    while n % p == 0:
        v += 1; n //= p
    return v


# ═══════ A. структурная теорема: D(N) = произведение цепей ═══════
def section_A():
    print("\n[A] D(N) ≅ ∏ цепей: делитель ↔ вектор показателей, делимость ⟺ покоординатное ≤")
    N = 360                                                  # 2³·3²·5 → показатели (3,2,1)
    f = factorize(N)
    primes = sorted(f); exps = [f[p] for p in primes]
    d_to_vec = lambda d: tuple(factorize(d).get(p, 0) for p in primes)
    divs = divisors(N)
    # биекция делители ↔ «коробка» ∏[0..aᵢ]; |D| = ∏(aᵢ+1)
    box = list(product(*[range(a + 1) for a in exps]))
    bijection = sorted(d_to_vec(d) for d in divs) == sorted(box) and len(divs) == prod(a + 1 for a in exps)
    check(f"D({N})↔коробка ∏[0..aᵢ], aᵢ={exps}: биекция делитель↔вектор показателей, |D|={len(divs)}=∏(aᵢ+1)",
          bijection)
    # делимость ⟺ покоординатное ≤ (различающий: проверяются ВСЕ пары, неверная пара провалила бы)
    order_iso = all((d2 % d1 == 0) == all(a <= b for a, b in zip(d_to_vec(d1), d_to_vec(d2)))
                    for d1 in divs for d2 in divs)
    check("делимость d₁|d₂ ⟺ показатели покоординатно ≤ ⟹ изоморфизм решётки произведению цепей", order_iso)


# ═══════ B. бесквадратное ⟺ булев куб ═══════
def section_B():
    print("\n[B] N БЕСКВАДРАТНО ⟺ D(N) ≅ Q_k (булев куб): делитель ↔ битовый вектор, делимость ⟺ ⊆")
    N = 210                                                  # 2·3·5·7, squarefree, k=4
    primes = sorted(factorize(N)); k = len(primes)
    divs = divisors(N)
    d_to_bits = lambda d: tuple(1 if d % p == 0 else 0 for p in primes)
    is_cube = sorted(d_to_bits(d) for d in divs) == sorted(product((0, 1), repeat=k)) and len(divs) == 2 ** k
    order = all((d2 % d1 == 0) == all(a <= b for a, b in zip(d_to_bits(d1), d_to_bits(d2)))
                for d1 in divs for d2 in divs)
    check(f"squarefree {N}: D≅Q_{k} (делитель↔битовый вектор), |D|={len(divs)}=2^{k}", is_cube)
    check("делимость ⟺ ⊆ битов ⟹ решётка делителей = булев куб Q_k", order)
    # различающий: 12=2²·3 НЕ куб (|D| не степень 2)
    d12 = divisors(12)
    pow2 = {2 ** i for i in range(6)}
    check("различающий: 12=2²·3 — |D(12)|=6 ∉ {2^i} ⟹ НЕ куб (есть квадрат) — нужна бесквадратность",
          len(d12) == 6 and 6 not in pow2)


# ═══════ C. число делителей ═══════
def section_C():
    print("\n[C] d(N) = ∏(aᵢ+1) (число делителей = размер коробки); squarefree ⟹ d(N)=2^ω(N)")
    for N in (360, 1000, 1):
        f = factorize(N)
        formula = prod(a + 1 for a in f.values()) if f else 1
        check(f"d({N})=∏(aᵢ+1)={formula} совпадает с прямым перебором делителей", formula == len(divisors(N)))
    check("squarefree: d(N)=2^ω(N) — например d(210)=2^4=16 = число вершин Q_4",
          len(divisors(210)) == 2 ** omega(210))


# ═══════ D. Мёбиус = знак вершины + включение-исключение ═══════
def section_D():
    print("\n[D] МЁБИУС: μ=(−1)^ω на squarefree, 0 на квадратах; Σ_{d|N} μ(d)=[N=1] (вкл-искл на кубе)")
    # μ — знак вершины куба (чётность числа простых); 0 вне куба (есть квадрат)
    signs_ok = mobius(1) == 1 and mobius(30) == -1 and mobius(210) == 1 and mobius(12) == 0 and mobius(8) == 0
    check("μ(1)=1, μ(2·3·5)=−1, μ(2·3·5·7)=+1 (=(−1)^ω, знак вершины); μ(2²·3)=μ(2³)=0 (квадрат)", signs_ok)
    # тождество Σ_{d|N} μ(d) = [N=1] = (1−1)^k на кубе простых = включение-исключение
    identity = all(sum(mobius(d) for d in divisors(N)) == (1 if N == 1 else 0)
                   for N in (1, 2, 6, 30, 210, 12, 36, 100))
    # различающий: для N>1 сумма строго НОЛЬ, для N=1 — единица (не константа)
    distinct = sum(mobius(d) for d in divisors(1)) == 1 and sum(mobius(d) for d in divisors(30)) == 0
    check("Σ_{d|N} μ(d) = [N=1]: единица при N=1, НОЛЬ при N>1 = (1−1)^k = вкл-искл на кубе делителей",
          identity and distinct)


# ═══════ E. самодвойственность d↦N/d ═══════
def section_E():
    print("\n[E] d↦N/d: биекция делителей, ОБРАЩАЕТ делимость (антиизоморфизм); squarefree ⟹ κ-антипод куба")
    N = 210
    divs = divisors(N)
    bij = sorted(N // d for d in divs) == divs
    anti = all((d2 % d1 == 0) == ((N // d1) % (N // d2) == 0) for d1 in divs for d2 in divs)
    check("d↦N/d — биекция делителей, обращает порядок (d₁|d₂ ⟺ N/d₂ | N/d₁): решётка самодвойственна",
          bij and anti)
    # на squarefree: N/d = битовое дополнение набора простых = κ:x↦1−x
    primes = sorted(factorize(N))
    bits = lambda d: tuple(1 if d % p == 0 else 0 for p in primes)
    kappa_ok = all(bits(N // d) == tuple(1 - b for b in bits(d)) for d in divs)
    check("squarefree: N/d = дополнение набора простых = κ (x↦1−x), антипод вершины в кубе Q_k", kappa_ok)


# ═══════ F. проекция на ранги ═══════
def section_F():
    print("\n[F] ПРОЕКЦИЯ НА РАНГИ: rank(N):=ω(N) = размерность куба Q_{ω(N)}; уровни = биномиальные C(k,j)")
    ranks = {N: omega(N) for N in (1, 2, 6, 30, 210)}
    check("rank(N)=ω(N) (различных простых): 1→Q₀, 2→Q₁, 6→Q₂, 30→Q₃, 210→Q₄",
          ranks == {1: 0, 2: 1, 6: 2, 30: 3, 210: 4})
    # уровни куба делителей squarefree = биномиальные коэффициенты (вес = число простых множителей)
    N, k = 210, 4
    levels = [0] * (k + 1)
    for d in divisors(N):
        levels[omega(d)] += 1
    check(f"уровни D(210)=Q_4 по весу = биномиальные {[comb(k, j) for j in range(k + 1)]} (= 1,4,6,4,1)",
          levels == [comb(k, j) for j in range(k + 1)])


# ═══════ G. локальность (Эйлер): мультипликативность ═══════
def section_G():
    print("\n[G] ЛОКАЛЬНОСТЬ (Эйлер): σ(N)=∏_p (1+p+…+p^a); мультипликативна, локальный множитель=этажи оси")
    sigma = lambda n: sum(divisors(n))
    N = 360
    f = factorize(N)
    local = prod(sum(p ** e for e in range(a + 1)) for p, a in f.items())
    check(f"σ({N})=∏_p Σ_{{e=0}}^{{a}} p^e = {local} (локальный множитель = сумма по этажам оси) = прямая Σделителей",
          sigma(N) == local)
    # различающий: σ мультипликативна на взаимно простых (σ(6)=σ(2)σ(3)), но НЕ аддитивна
    mult = sigma(6) == sigma(2) * sigma(3)
    not_add = sigma(6) != sigma(2) + sigma(3)
    check("σ мультипликативна на coprime: σ(6)=σ(2)·σ(3)=3·4=12, и НЕ аддитивна (≠3+4) — структура произведения",
          mult and not_add)


# ═══════ H. D(бесквадратного N) = булева алгебра ═══════
def section_H():
    print("\n[H] D(бесквадратного N) = БУЛЕВА АЛГЕБРА: дополнение d↦N/d (¬), де Морган (⊥=1,⊤=N,∧=gcd,∨=lcm)")
    N = 210
    D = divisors(N)
    # дополнение ¬d=N/d: d∧¬d=⊥(1), d∨¬d=⊤(N)
    comp = all(gcd(d, N // d) == 1 and lcm(d, N // d) == N for d in D)
    demorgan = all(N // gcd(a, b) == lcm(N // a, N // b) for a in D for b in D)
    check("дополнение ¬d=N/d: gcd(d,N/d)=1 (низ ⊥) и lcm(d,N/d)=N (верх ⊤) — булево дополнение", comp)
    check("де Морган N/gcd(a,b)=lcm(N/a,N/b) ⟹ D(squarefree) = булева алгебра (⊥=1,⊤=N,∧=gcd,∨=lcm,¬=N/d)",
          demorgan)
    # различающий: на НЕ-squarefree (12) дополнение ломается — d=2: gcd(2,6)=2≠1, нет комплемента
    check("различающий: 12=2²·3 — gcd(2,12/2)=gcd(2,6)=2≠1 ⟹ нет дополнения ⟹ не булева (нужна бесквадратность)",
          gcd(2, 12 // 2) != 1)


# ═══════ I. × взаимно простых = декартово произведение кубов ═══════
def section_I():
    print("\n[I] × ВЗАИМНО ПРОСТЫХ = Q_a × Q_b = Q_(a+b): умножение склеивает оси, ранг СКЛАДЫВАЕТСЯ")
    M, K = 6, 35                                              # coprime: 2·3 и 5·7
    cart = len(divisors(M)) * len(divisors(K)) == len(divisors(M * K))
    rank_add = omega(M) + omega(K) == omega(M * K)
    check(f"|D(6)|·|D(35)|={len(divisors(M))}·{len(divisors(K))}=|D(210)|={len(divisors(M*K))} и ω 2+2=4 ⟹ Q₂×Q₂=Q₄",
          cart and rank_add)
    # различающий: НЕ взаимно простые (6·10) — оси перекрылись, ранг НЕ складывается
    check("различающий: НЕ coprime 6·10=60 — ω(60)=3 ≠ ω(6)+ω(10)=4 (оси перекрылись, не Q_(a+b))",
          omega(60) != omega(6) + omega(10))


# ═══════ J. факториал = число максимальных цепей куба ═══════
def section_J():
    print("\n[J] ФАКТОРИАЛ = число МАКСИМАЛЬНЫХ ЦЕПЕЙ куба Q_k = k! (все обходы ⊥→⊤); n! не бесквадратно")
    def max_chains(k):                                       # пути ∅→[k] шагом +1 элемент = порядки осей
        def cnt(s):
            return 1 if len(s) == k else sum(cnt(s | {i}) for i in range(k) if i not in s)
        return cnt(frozenset())
    check("число макс. цепей куба Q_k (путей ⊥→⊤ = порядков добавления осей) = k! для k=1..5",
          all(max_chains(k) == factorial(k) for k in range(1, 6)))
    # n! сильно надстроено над кубом: Лежандр v_p(n!)=Σ⌊n/pⁱ⌋, не бесквадратно
    def legendre(n, p):
        s, pk = 0, p
        while pk <= n: s += n // pk; pk *= p
        return s
    f6 = factorize(factorial(6))
    check("v_p(n!)=Σ⌊n/pⁱ⌋ (Лежандр): v₂(6!)=4 совпало; n! НЕ бесквадратно ⟹ живёт высоко над кубом (этажи)",
          f6.get(2, 0) == legendre(6, 2) and any(a >= 2 for a in f6.values()))


# ═══════ K. Мёбиус: обращение ζ, слепота к этажам, предел s→1 (∞) ═══════
def section_K():
    print("\n[K] МЁБИУС μ: ОБРАЩЕНИЕ ζ (1/ζ=Σμ/nˢ=∏(1−p⁻ˢ)); слеп к этажам (≠0⟺вершина куба); предел s→1=∞")
    # μ≠0 ⟺ N бесквадратно ⟺ вершина куба: μ ВИДИТ только чистый куб, слепа к ^-надстройке (этажам)
    blind = all((mobius(N) != 0) == all(a == 1 for a in factorize(N).values()) for N in range(1, 200))
    check("μ(N)≠0 ⟺ N бесквадратно (вершина куба); μ=0 на этажах ⟹ μ видит ТОЛЬКО чистый куб (слепа к ^)",
          blind)
    # обращение Дирихле: μ*1=δ (μ обратен константе 1) — это и есть Σ_{d|N}μ(d)=[N=1]
    check("свёртка μ*1=δ (Σ_{d|N}μ(d)=[N=1]): μ = ОБРАТНЫЙ к константе 1 в кольце Дирихле (= вкл-искл)",
          all(sum(mobius(d) for d in divisors(N)) == (1 if N == 1 else 0) for N in range(1, 100)))
    # 1/ζ(s)=Σμ(n)/nˢ=∏(1−p⁻ˢ); при s=2 → 6/π² (μ ОБРАЩАЕТ Эйлерово произведение)
    s, target = 2.0, 6.0 / pi ** 2
    msum = sum(mobius(n) / n ** s for n in range(1, 20000))
    primes = [p for p in range(2, 20000) if all(p % q for q in range(2, int(p ** 0.5) + 1))]
    prodp = prod((1 - p ** (-s)) for p in primes)
    check(f"1/ζ(2)=Σμ(n)/n²=∏(1−p⁻²)=6/π²≈{target:.5f}: μ ОБРАЩАЕТ Эйлерово произведение (∏ vs Σ)",
          abs(msum - target) < 1e-3 and abs(prodp - target) < 1e-3)
    # ПРЕДЕЛ s→1: ζ имеет ПОЛЮС (гарм. ряд s=1 расходится ~ln N →∞), а s=2 насыщается (различающий)
    H = [sum(1.0 / n for n in range(1, 10 ** k + 1)) for k in (2, 3, 4)]          # s=1
    Z2 = [sum(1.0 / n ** 2 for n in range(1, 10 ** k + 1)) for k in (2, 3, 4)]    # s=2
    harm_diverges = H[0] < H[1] < H[2] and (H[2] - H[1]) > 0.5                    # растёт ~ln10≈2.3/порядок
    z2_saturates = abs(Z2[2] - Z2[1]) < 0.01                                      # → π²/6, конечно
    check("полюс s=1: Σ1/n РАСХОДИТСЯ (растёт ~ln N →∞), а Σ1/n² насыщается ⟹ ζ имеет полюс в s=1 (=∞)",
          harm_diverges and z2_saturates)
    # 1/ζ = Σμ/nˢ → 0 у полюса: μ-сторона ГАСНЕТ на ∞-полюсе ζ
    check("1/ζ=Σμ/nˢ → 0 у полюса s→1 (μ-сторона гаснет на ∞): 1/H(N) монотонно → 0",
          1.0 / H[0] > 1.0 / H[1] > 1.0 / H[2] and 1.0 / H[2] < 0.2)
    print("   → μ ложится в ДВА места: ЛОКАЛЬНО — знак вершины куба (−1)^ω (●); ПРЕДЕЛЬНО — обращение ζ у ∞-")
    print("     полюса (●). Сумма Мертенса M(x)=Σ_{n≤x}μ(n) — ∞-предельный объект, её рост ⟺ σ½ (Риман, ○).")


# ═══════ L. полюса 0 и ∞ (отсечения; первое различение 0→1) ═══════
def section_L():
    print("\n[L] ПОЛЮСА 0 и ∞ (отсечения-фон): 0→1 = первое различение (аддит. инвариант); κ:0↔∞, центр √N=σ½")
    # 0 = нижний полюс: нейтрал +, ПОГЛОТИТЕЛЬ × (стирает) — вне мультипликативного куба
    check("0 = нижний полюс: нейтрал + (0+n=n) и ПОГЛОТИТЕЛЬ × (0·n=0, стирает) ⟹ вне мультипл. куба (фон)",
          all(0 + n == n for n in range(6)) and all(0 * n == 0 for n in range(6)))
    # первое различение из фона: 0→1 (succ) = аддитивный инвариант (единица); 1 = низ ⊥ куба (ω=0)
    check("0→1 (succ) = ПЕРВОЕ различение из фона = аддитивный инвариант (единица счёта); 1=низ ⊥ куба (ω=0)",
          (0 + 1 == 1) and omega(1) == 0)
    # κ:d↦N/d меняет низ↔верх (полюса 1↔N); неподвижная = √N = центр = σ½ (для квадрата N)
    N = 36                                                   # √36=6 — центр существует
    check("κ:d↦N/d меняет полюса (1↔N=низ↔верх); неподвижная=√N=центр=σ½ (N=36 ⟹ √N=6 неподвижна)",
          (N // 1 == N) and (N // N == 1) and (N // 6 == 6))
    # ∞ = верхний полюс: ранг неограничен — примориал даёт Q_k для ЛЮБОГО k, верха ряда нет
    primorial = [1, 2, 6, 30, 210, 2310]
    check("∞ = верхний полюс: ранг НЕОГРАНИЧЕН — примориалы p₁···p_k дают Q_k для любого k (верха ряда нет)",
          [omega(p) for p in primorial] == [0, 1, 2, 3, 4, 5])


# ═══════ M. алгоритм Евклида и тождество Безу (фундамент gcd = ∧) ═══════
def section_M():
    print("\n[M] ЕВКЛИД + БЕЗУ: gcd через остатки (=∧ решётки); gcd(a,b)=ax+by (конструктивный инфимум)")
    def euclid(a, b):
        while b: a, b = b, a % b
        return a
    def ext(a, b):                                          # расширенный Евклид: (g, x, y), g=ax+by
        if b == 0: return a, 1, 0
        g, x, y = ext(b, a % b)
        return g, y, x - (a // b) * y
    check("алгоритм Евклида (цепочка остатков) даёт gcd = ∧ решётки D — фундамент инфимума",
          all(euclid(a, b) == gcd(a, b) for a, b in [(12, 18), (17, 5), (240, 46), (100, 60)]))
    bezout = all((lambda g, x, y: g == gcd(a, b) and a * x + b * y == g)(*ext(a, b))
                 for a, b in [(12, 18), (17, 5), (240, 46)])
    check("Безу: gcd(a,b)=ax+by (расширенный Евклид) — инфимум выразим линейно; конструктивный ∧", bezout)
    # различающий: coprime ⟺ gcd=1 (Безу даёт 1), не-coprime ⟺ >1
    check("различающий: gcd(17,5)=1 (coprime, ∃ 17x+5y=1), gcd(12,18)=6>1 (общий делитель)",
          gcd(17, 5) == 1 and gcd(12, 18) == 6)


# ═══════ N. КТО: ℤ/n ≅ ∏ ℤ/pᵢ^aᵢ = моноидальность □ на вычетах ═══════
def section_N():
    print("\n[N] КТО (китайская т.): ℤ/n ≅ ∏ ℤ/pᵢ^aᵢ — кольцевой изоморфизм = □ на ВЫЧЕТАХ (2-я реализация)")
    n, parts = 12, [4, 3]                                   # 12 = 4·3, части взаимно просты
    proj = lambda x: tuple(x % m for m in parts)
    biject = len({proj(x) for x in range(n)}) == n
    addhom = all(proj((a + b) % n) == tuple((proj(a)[i] + proj(b)[i]) % parts[i] for i in range(len(parts)))
                 for a in range(n) for b in range(n))
    mulhom = all(proj((a * b) % n) == tuple((proj(a)[i] * proj(b)[i]) % parts[i] for i in range(len(parts)))
                 for a in range(n) for b in range(n))
    check("ℤ/12 → ℤ/4×ℤ/3 (x↦(x mod 4, x mod 3)): биекция", biject)
    check("КТО сохраняет + и × (кольцевой изоморфизм) ⟹ ℤ/n≅∏ℤ/pᵢ^aᵢ = моноидальность □ на вычетах",
          addhom and mulhom)
    # различающий: НЕ взаимно простые части [4,6] — НЕ изоморфизм: |ℤ/4×ℤ/6|=24≠12 (не сюръекция)
    check("различающий: части [4,6] НЕ coprime (gcd=2) ⟹ |ℤ/4×ℤ/6|=24≠12, НЕ изоморфизм; КТО требует coprime осей",
          gcd(4, 6) == 2 and 4 * 6 != 12 and 4 * 3 == 12)


# ═══════ O. φ Эйлера: мультипликативна (□), φ=μ*Id, Σφ(d)=n ═══════
def section_O():
    print("\n[O] φ ЭЙЛЕРА (тотиент): мультипликативна (=□); φ(p^a)=p^a−p^(a−1); Σ_{d|n}φ(d)=n; φ=μ*Id")
    mult = all(phi(m * k) == phi(m) * phi(k) for m, k in [(4, 3), (5, 6), (7, 10), (8, 9)] if gcd(m, k) == 1)
    pa = all(phi(p ** a) == p ** a - p ** (a - 1) for p, a in [(2, 3), (3, 2), (5, 2)])
    check("φ мультипликативна φ(mn)=φ(m)φ(n) на coprime (=□, локальна по осям); φ(p^a)=p^a−p^(a−1)",
          mult and pa)
    check("Σ_{d|n}φ(d)=n (свёртка φ*1=Id): сумма φ по кубу делителей восстанавливает n",
          all(sum(phi(d) for d in divisors(n)) == n for n in range(1, 60)))
    check("φ=μ*Id (φ(n)=Σ_{d|n}μ(d)·n/d): φ через обращение Мёбиуса = включение-исключение на кубе",
          all(phi(n) == sum(mobius(d) * (n // d) for d in divisors(n)) for n in range(1, 60)))


# ═══════ P. v_p нормирование = высота этажа; формула произведения ═══════
def section_P():
    print("\n[P] v_p НОРМИРОВАНИЕ = ВЫСОТА ЭТАЖА: v_p(mn)=v_p(m)+v_p(n) (×→+); |n|_p=p^(−v_p); ∏|n|_v=1")
    add = all(vp(m * k, p) == vp(m, p) + vp(k, p) for p in (2, 3, 5) for m, k in [(4, 6), (8, 12), (9, 15)])
    coord = all(vp(360, p) == factorize(360).get(p, 0) for p in (2, 3, 5))
    check("v_p(mn)=v_p(m)+v_p(n): p-адическое НОРМИРОВАНИЕ (превращает × в +); v_p = координата этажа оси p",
          add and coord)
    # формула произведения: ∏_p |n|_p · |n|_∞ = ∏_p p^(−v_p) · n = (1/n)·n = 1 (этаж сшит с архимедовым |·|∞)
    prodform = all(abs(prod(p ** (-vp(n, p)) for p in factorize(n)) * n - 1.0) < 1e-12 for n in (12, 30, 360))
    check("|n|_p=p^(−v_p); формула произведения ∏_p|n|_p·|n|_∞=1 ⟹ этаж (v_p) сшит с архимедовой стороной |·|∞",
          prodform)


# ═══════ Q. малая Ферма / Эйлер: группа (ℤ/n)* ═══════
def section_Q():
    print("\n[Q] МАЛАЯ ФЕРМА / ЭЙЛЕР: a^φ(n)≡1 (mod n) для gcd(a,n)=1; (ℤ/n)* группа, для простого циклична")
    fermat = all(pow(a, phi(n), n) == 1 for n in (7, 12, 15, 20) for a in range(1, n) if gcd(a, n) == 1)
    grp = all(len([a for a in range(1, n) if gcd(a, n) == 1]) == phi(n) for n in (7, 12, 15))
    check("a^φ(n)≡1 (mod n) при gcd(a,n)=1 (Эйлер); |(ℤ/n)*|=φ(n) — порядок группы обратимых вычетов",
          fermat and grp)
    def order(a, p):
        o, x = 1, a % p
        while x != 1: x = x * a % p; o += 1
        return o
    # для простого p группа (ℤ/p)* ЦИКЛИЧНА: есть первообразный корень (элемент порядка p−1)
    check("для простого p (ℤ/p)* ЦИКЛИЧНА — ∃ первообразный корень (g порядка p−1): mod 7 это g=3 (порядок 6)",
          order(3, 7) == 6 and any(order(g, 11) == 10 for g in range(2, 11)))


# ═══════ R. функторный словарь: Λ — настоящий функтор машины ═══════
def section_R():
    print("\n[R] ФУНКТОРНЫЙ СЛОВАРЬ: Λ:S↦∏_{p∈S}p — ФУНКТОР (сохраняет порядок, □, κ) ⟹ ● не узнавание")
    primes = [2, 3, 5, 7]
    Lam = lambda S: prod(primes[i] for i in S) if S else 1
    subs = [set(c) for r in range(len(primes) + 1)
            for c in __import__("itertools").combinations(range(len(primes)), r)]
    # (1) лифт Λ/H: сохраняет порядок ⊆ ↦ | (функтор частично упорядоченных множеств)
    order = all((S <= T) == (Lam(T) % Lam(S) == 0) for S in subs for T in subs)
    check("Λ сохраняет порядок: S⊆T ⟺ Λ(S)|Λ(T) — функтор (кат. множеств простых → числа с делимостью)",
          order)
    # (2) моноидальность □: Λ(S⊔T)=Λ(S)·Λ(T) для disjoint (□ ↦ × взаимно простых)
    mono = all(Lam(S | T) == Lam(S) * Lam(T) for S in subs for T in subs if not (S & T))
    check("Λ моноидален: Λ(S⊔T)=Λ(S)·Λ(T) (□ куба ↦ × coprime) — функтор сохраняет тензор Q_a□Q_b=Q_(a+b)",
          mono)
    # (3) κ: Λ(дополнение)=N/Λ(S) (κ куба ↦ d↦N/d)
    N, full = prod(primes), set(range(len(primes)))
    kappa = all(Lam(full - S) == N // Lam(S) for S in subs)
    check("Λ коммутирует с κ: Λ(∁S)=N/Λ(S) (дополнение куба ↦ d↦N/d) ⟹ Λ переносит ВСЕ функторы (●)",
          kappa)
    print("   → ВЫВОД: на бесквадратных числах Λ — изоморфизм категорий (множества простых ≅ числа с |);")
    print("     функторы машины Λ/□/κ/H реализованы СТРОГО (●), не 'узнаны'. Узнавание (◐) — только σ½=Re=½.")


