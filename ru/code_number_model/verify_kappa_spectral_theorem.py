"""
verify_kappa_spectral_theorem.py — почему e^{iLπ}=I НЕ совпадение ранга 3, а теорема о κ на каждом ранге.

Продолжение заметки «π через e^{iπL}=I — верно, но тривиально, спектр {0,4,6}
чётный». Здесь — ПОЧЕМУ спектр чётный: это не свойство именно октаэдра, а ТЕОРЕМА о графе «полный минус
паросочетание», верная для ЛЮБОГО паросочетания и ЛЮБОГО m, и в частности — для κ на КАЖДОМ ранге n≥3
(не только n=3). Корень — κ есть ИНВОЛЮЦИЯ БЕЗ НЕПОДВИЖНЫХ ТОЧЕК на активном носителе U_n (уже доказано);
это единственное, что нужно для теоремы. ★ВТОРОЙ независимый путь к той же связи κ↔π — буквальное
вложение цикла R1 (C₆ на ранге 3) в шесть корней из единицы (T=e^{iπ/3}, T³=κ). ★МЕТОДОЛОГИЧЕСКИЙ урок:
первая проверка «на другом графе» взяла K₄ как «постороннее» сравнение — но K₄ есть ПОЛНЫЙ (невыколотый)
Q₂, вырожденный член ТОЙ ЖЕ конструкции, не честный контроль; честный контроль — графы вне семейства
«полный минус паросочетание» (звезда), и честная общность — рангИ ОДНОЙ конструкции (n=2..6, секция D/E).
Регистр: ● вся теорема (доказана и проверена); ◐ отождествление с «истинной природой π» — НЕ утверждается
(см. секцию G/F-итог); ✗ ничего не убито — это уточнение, не отказ.

  A. ★ОБЩАЯ ТЕОРЕМА: K_m минус ЛЮБОЕ паросочетание → спектр {0,m−2(×m/2),m(×m/2−1)} — для люб. m,m чётно.
  B. J и P КОММУТИРУЮТ (P сохраняет вектор «все единицы») — механизм теоремы, не специфика κ.
  C. СЛЕДСТВИЕ: e^{iLπ}=I ВСЕГДА (спектр всегда чётный, не «совпадение» рангов 2,3).
  D. ПРОВЕРКА ПО РАНГАМ n=2..6 (наша конструкция U_n минус κ-паросочетание): теорема держится на каждом.
  E. МЕТОДОЛОГИЯ: K₄=вырожденный Q₂ (не контроль); честный контроль=звезда (вне семейства, не работает).
  F. КОРЕНЬ: κ²=id БЕЗ неподвижных точек на U_n (n≥1) — единственное, что нужно; теорема не про октаэдр.
  G. ★ТРЕТИЙ ПУТЬ: C₆ (ранг 3, R1-цикл) = буквально 6 корней из единицы; T=e^{iπ/3}, T⁶=1, T³=κ=e^{iπ}=−1.
  H. ИТОГ + страж: что доказано, что — узнавание, что не утверждается.
"""
from __future__ import annotations
import numpy as np
import cmath, math

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

def expm_herm(M, t):
    """e^{itM} для эрмитовой M через диагонализацию (без scipy)."""
    w, V = np.linalg.eigh(M)
    return V @ np.diag(np.exp(1j * t * w)) @ V.conj().T

def complete_minus_matching(m, pairs):
    A = np.ones((m, m)) - np.eye(m)
    for a, b in pairs:
        A[a, b] = 0; A[b, a] = 0
    return np.diag(A.sum(1)) - A   # Лапласиан


# ═══════════════ A. общая теорема: K_m минус ЛЮБОЕ паросочетание ═══════════════
def section_A():
    print("\n[A] ★ОБЩАЯ ТЕОРЕМА: K_m минус ЛЮБОЕ паросочетание → спектр {0,m−2(×m/2),m(×m/2−1)}")
    rng = np.random.RandomState(0)
    all_ok = True
    for m in (4, 6, 8, 10):
        verts = list(range(m)); rng.shuffle(verts)
        pairs = [(verts[2 * i], verts[2 * i + 1]) for i in range(m // 2)]   # ПРОИЗВОЛЬНОЕ паросочетание
        L = complete_minus_matching(m, pairs)
        spec = np.sort(np.linalg.eigvalsh(L))
        predicted = sorted([0] + [m] * (m // 2 - 1) + [m - 2] * (m // 2))
        ok = np.allclose(spec, predicted, atol=1e-8)
        all_ok = all_ok and ok
        print(f"   m={m:>2}, случайное паросочетание {pairs}: спектр={np.round(spec,2)} = "
              f"предсказание {predicted}: {ok}")
    check("теорема верна для ПРОИЗВОЛЬНОГО паросочетания (не только κ) и произвольного чётного m "
          "⟹ это факт о структуре «полный граф минус паросочетание», не о конкретном графе", all_ok)


# ═══════════════ B. J и P коммутируют ═══════════════
def section_B():
    print("\n[B] J и P КОММУТИРУЮТ (P сохраняет вектор «все единицы») — механизм теоремы")
    m = 8
    pairs = [(0, 1), (2, 3), (4, 5), (6, 7)]
    J = np.ones((m, m))
    P = np.eye(m)
    for a, b in pairs:
        P[a, a] = 0; P[b, b] = 0; P[a, b] = 1; P[b, a] = 1
    comm = np.allclose(J @ P, P @ J)
    ones = np.ones(m)
    fixes_ones = np.allclose(P @ ones, ones)
    check(f"JP=PJ:{comm}; P фиксирует вектор «все 1» (P·𝟙=𝟙):{fixes_ones} ⟹ J,P СОВМЕСТНО диагонализуемы "
          f"⟹ спектр L=(m−1)I−J+P считается ПОКООРДИНАТНО (секция A — прямое следствие)",
          comm and fixes_ones)


# ═══════════════ C. следствие: e^{iLπ}=I всегда ═══════════════
def section_C():
    print("\n[C] СЛЕДСТВИЕ: e^{iLπ}=I ВСЕГДА (спектр всегда чётный для ЛЮБОГО чётного m, не «совпадение»)")
    all_ok = True
    for m in (4, 6, 8, 10, 12):
        pairs = [(2 * i, 2 * i + 1) for i in range(m // 2)]
        L = complete_minus_matching(m, pairs)
        U = expm_herm(L, math.pi)
        ok = np.allclose(U, np.eye(m), atol=1e-8)
        all_ok = all_ok and ok
        print(f"   m={m:>2}: e^(iLπ)=I: {ok}")
    check("для ЛЮБОГО чётного m (не только m=6 у октаэдра) e^{iLπ}=I ⟹ возврат на π — СВОЙСТВО СЕМЕЙСТВА "
          "«полный минус паросочетание», не привилегия рангового объекта", all_ok)


# ═══════════════ D. проверка по рангам нашей конструкции n=2..6 ═══════════════
def kappa_pairs_of_rank(n):
    full = (1 << n) - 1
    U = [x for x in range(1 << n) if x not in (0, full)]
    idx = {v: i for i, v in enumerate(U)}
    pairs = []
    for x in U:
        y = full ^ x
        if y in idx and idx[x] < idx[y]:
            pairs.append((idx[x], idx[y]))
    return U, pairs

def section_D():
    print("\n[D] ПРОВЕРКА ПО РАНГАМ n=2..6 (U_n минус κ-паросочетание): теорема держится на каждом")
    all_ok = True
    for n in (2, 3, 4, 5, 6):
        U, pairs = kappa_pairs_of_rank(n)
        m = len(U)
        L = complete_minus_matching(m, pairs)
        spec = np.sort(np.linalg.eigvalsh(L))
        predicted = sorted([0] + [m] * (m // 2 - 1) + [m - 2] * (m // 2))
        spec_ok = np.allclose(spec, predicted, atol=1e-7)
        U_pi = expm_herm(L, math.pi)
        return_ok = np.allclose(U_pi, np.eye(m), atol=1e-7)
        all_ok = all_ok and spec_ok and return_ok
        print(f"   ранг {n}: |U_{n}|=m={m:>3}, κ-пар={len(pairs):>2}; спектр=предсказанию:{spec_ok}; "
              f"e^(iLπ)=I:{return_ok}")
    check("на ВСЕХ проверенных рангах 2..6 теорема и следствие держатся без исключения ⟹ это инвариант "
          "ВСЕЙ ранговой лестницы, не особенность ранга 3", all_ok)


# ═══════════════ E. методология: K4 не контроль, звезда — честный контроль ═══════════════
def section_E():
    print("\n[E] МЕТОДОЛОГИЯ: K₄=вырожденный (невыколотый) Q₂, НЕ посторонний контроль; честный контроль=звезда")
    # K4 = ПОЛНЫЙ (невыколотый) Q_2: на 2 битах макс.расстояние=2=R2, выкалывать нечего
    full_Q2 = [(0, 1) for _ in range(0)]  # нет паросочетания вообще — это K4 БЕЗ вычитания
    A_K4 = np.ones((4, 4)) - np.eye(4)
    L_K4 = np.diag(A_K4.sum(1)) - A_K4
    spec_K4 = np.sort(np.linalg.eigvalsh(L_K4))
    is_K4_full_Q2 = np.allclose(spec_K4, [0, 4, 4, 4])
    # выколотый U_2 (как на др. рангах): всего 2 точки = САМИ κ-пара ⟹ граф после вычитания ПУСТ
    U2, pairs2 = kappa_pairs_of_rank(2)
    degenerate = (len(U2) == 2 and len(pairs2) == 1)
    check(f"K₄: спектр={spec_K4} = спектр K_4 БЕЗ вычитания (паросочетания нет, т.к. на 2 битах нечего "
          f"выкалывать — макс.расстояние уже =2=R2):{is_K4_full_Q2} ⟹ K₄ НЕ 'посторонний граф', а "
          f"ВЫРОЖДЕННЫЙ член СЕМЬИ (полный Q₂, паросочетание тривиально пусто), не честный контроль; "
          f"истинный U_2 (выколотый) = {len(U2)} точки = сама κ-пара, граф ПУСТ (вырождение):{degenerate}",
          is_K4_full_Q2 and degenerate)
    # честный контроль: звезда K_{1,3} — НЕ принадлежит семейству "полный минус паросочетание"
    A_star = np.array([[0, 1, 1, 1], [1, 0, 0, 0], [1, 0, 0, 0], [1, 0, 0, 0]], dtype=float)
    L_star = np.diag(A_star.sum(1)) - A_star
    spec_star = np.sort(np.linalg.eigvalsh(L_star))
    U_star = expm_herm(L_star, math.pi)
    star_fails = not np.allclose(U_star, np.eye(4), atol=1e-8)
    check(f"звезда K_(1,3): спектр={np.round(spec_star,3)} (есть нечётное {1}); e^(iLπ)=I ЛОЖНО:{star_fails} "
          f"⟹ звезда ВНЕ семейства «полный минус паросочетание» ⟹ честный отрицательный контроль "
          f"(в отличие от K₄, который был вырожденным членом ТОЙ ЖЕ семьи, не контролем вообще)",
          star_fails)


# ═══════════════ F. корень: κ²=id без неподвижных точек — единственное условие ═══════════════
def section_F():
    print("\n[F] КОРЕНЬ: κ²=id БЕЗ неподвижных точек на U_n (n≥1) — единственное, что нужно теореме")
    all_no_fix = True
    for n in (1, 2, 3, 4, 5):
        full = (1 << n) - 1
        U = [x for x in range(1 << n) if x not in (0, full)]
        no_fixed = all((full ^ x) != x for x in U)   # κ(x)=x невозможно на бесквадратном носителе
        kappa_invol = all((full ^ (full ^ x)) == x for x in U)   # κ²=id
        all_no_fix = all_no_fix and no_fixed and kappa_invol
        print(f"   ранг {n}: κ²=id:{kappa_invol}; неподвижных точек НЕТ на U_{n}:{no_fixed}")
    check("κ — инволюция БЕЗ неподвижных точек на КАЖДОМ U_n (n≥1, уже доказано для D(N)) ⟹ это "
          "ЕДИНСТВЕННОЕ структурное условие, нужное теореме (секции A-B); теорема НЕ про октаэдр специально, "
          "она про κ — и κ есть на каждом ранге по построению", all_no_fix)


# ═══════════════ G. третий путь: C6 = шесть корней из единицы ═══════════════
def section_G():
    print("\n[G] ★ТРЕТИЙ ПУТЬ: C₆ (ранг 3, R1-цикл) = буквально 6 корней из единицы; T=e^(iπ/3), T³=κ=e^(iπ)=−1")
    T = cmath.exp(1j * math.pi / 3)
    powers = [T ** k for k in range(7)]
    period6 = abs(powers[6] - 1) < 1e-9
    half_is_kappa = abs(powers[3] - (-1)) < 1e-9
    check(f"T=e^(iπ/3): T⁶=1:{period6}; T³=−1 (=e^(iπ), κ-аналог по знаку):{half_is_kappa} ⟹ цикл R1 (C₆, "
          f"ранг 3) буквально ВКЛАДЫВАЕТСЯ в 6-е корни из единицы — НЕЗАВИСИМЫЙ от спектральной теоремы "
          f"(A-D) путь к той же связи κ↔π: ОДИН — через ТОЧКИ цикла, ДРУГОЙ — через СПЕКТР всего графа",
          period6 and half_is_kappa)
    print("   → два пути НЕЗАВИСИМЫ: спектральный (A-D, любой ранг, весь граф) и точечный (G, только ранг 3,")
    print("     только цикл R1) — оба упираются в одно и то же e^{iπ}=−1, но разными механизмами.")


# ═══════════════ H. итог + страж ═══════════════
def section_H():
    print("\n[H] СТРАЖ ●◐○")
    print("   ● вся теорема: общая формула спектра (A,B), следствие e^{iLπ}=I (C), проверка по рангам (D),")
    print("     методология K₄/звезда (E), корень κ²=id-без-фикса (F), вложение C₆=6 корней (G).")
    print("   ◐ отождествление: «возврат на π» = ТА ЖЕ константа π, что геометрическая (через e^{iπ}=−1,")
    print("     Эйлер) — форма доказана, но это ДОПОЛНИТЕЛЬНОЕ место появления π, не замена геометрии.")
    print("   ✗ НЕ утверждается: «π — это не отношение длины окружности к диаметру» (источник-документ так")
    print("     заявлял) — это overclaim; здесь заявляется честно: π ТАКЖЕ forced появляется здесь, как")
