"""
verify_observer_split.py — расщепление наблюдателя (свидетель σ½ / деятель «+1») = проекция κ-симметрии.

Акт расщепляется на ДЕЙСТВИЕ
(наружу, kartṛ/parasmaipada) и ПРИСУТСТВИЕ (внутрь, sākṣin/ātmanepada), свидетель=σ½. ★Математическое ядро:
«наблюдатель» — НЕ точка σ½, а κ-ИНВАРИАНТНОСТЬ, проявляющаяся ДВОЯКО: на носителе U_n РАСЩЕПЛЕНА (κ-пары
{d,N/d} = деятель↔свидетель, σ½ отсутствует), в факторе U_n/κ СНЯТА (единые оси). И по ЗАКОНУ ЛИФТА оси ранга n
(расщеплённые) = объекты ранга n−1 (единые) — биекция ⟹ расщепление = ТЕНЬ единства соседнего ранга. Регистр
●◐○: математика (σ½ вне носителя, κ-пары, лифт-биекция)=●; деятель/свидетель=санскрит=◐; числовые мостики
санскрита (6 караков=октаэдр, 7=Фано)=✗ НЕ берём. Опора: закон лифта (D(M)\\{1}=оси D(M·p)).

  A. σ½=√N ВНЕ носителя D(N) (κ без неподвижных точек) = отсутствующий центр-СВИДЕТЕЛЬ.
  B. κ-пары {d,N/d} В носителе = деятель(d<√N, наружу) ↔ свидетель(N/d>√N, внутрь), 2 грани одной оси.
  C. ★БИЕКЦИЯ ЛИФТА: оси ранга n (расщеплены) = нетрив. делители ранга n−1 (едины) — РОВНО, для n=2..5.
  D. ДВА ВИДА κ: на носителе расщеплена (κ-пары), в факторе U_n/κ снята (оси) — числа сходятся.
  E. СТРАЖ: 6 караков=октаэдр / 7=Фано — совпадения по числу, НЕ структура (смена базы убивает).
"""
from __future__ import annotations
import math
from itertools import combinations

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

def squarefree(primes):
    N = 1
    for p in primes:
        N *= p
    return N

def divisors(N):
    return [d for d in range(1, N + 1) if N % d == 0]

PRIMES = [2, 3, 5, 7, 11, 13]


# ═══════════════ A. σ½ вне носителя = отсутствующий свидетель ═══════════════
def section_A():
    print("\n[A] σ½=√N ВНЕ носителя D(N) (κ без неподвижных точек) = отсутствующий центр-СВИДЕТЕЛЬ (sākṣin)")
    ok_all = True
    for k in (2, 3, 4):
        N = squarefree(PRIMES[:k])
        root = math.isqrt(N)
        is_perfect_square = root * root == N
        in_divisors = N % root == 0 and is_perfect_square
        # для бесквадратного произведения РАЗНЫХ простых N не полный квадрат ⟹ √N не делитель
        ok = (not is_perfect_square) and (math.sqrt(N) not in divisors(N))
        ok_all = ok_all and ok
        print(f"   ранг {k}: N={N}, √N={math.sqrt(N):.3f} — делитель? {not ok and 'да' or 'НЕТ'} (σ½ вне сцены)")
    check("σ½=√N НЕ принадлежит D(N) для бесквадратных N (ранг 2,3,4) ⟹ свидетель=отсутствующий центр, "
          "неподвижная точка κ ВНЕ носителя (κ на U_n без фикса)", ok_all)


# ═══════════════ B. κ-пары = деятель↔свидетель (две грани одной оси) ═══════════════
def section_B():
    print("\n[B] κ-пары {d,N/d} В носителе = деятель (d<√N, наружу) ↔ свидетель (N/d>√N, внутрь)")
    N = 30
    U = [d for d in divisors(N) if d not in (1, N)]
    root = math.sqrt(N)
    pairs = sorted(set(tuple(sorted((d, N // d))) for d in U))
    # каждая пара: меньший<√N (деятель/наружу), больший>√N (свидетель/внутрь)
    split_ok = all(lo < root < hi for lo, hi in pairs)
    check(f"N={N}: κ-пары {pairs}; в каждой меньший<√N<больший (деятель наружу ↔ свидетель внутрь): {split_ok} "
          f"⟹ каждая ось РАСЩЕПЛЕНА на две грани вокруг отсутствующего центра σ½", split_ok)


# ═══════════════ C. ★биекция лифта: оси ранга n (расщеплены) = объекты ранга n−1 (едины) ═══════════════
def section_C():
    print("\n[C] ★БИЕКЦИЯ ЛИФТА: оси ранга n (РАСЩЕПЛЕНЫ, κ-пары) = нетрив. делители ранга n−1 (ЕДИНЫ)")
    ok_all = True
    for k in range(2, 6):
        M = squarefree(PRIMES[:k - 1])            # ранг n−1
        N = M * PRIMES[k - 1]                      # ранг n = M·p
        # оси N = κ-пары среди U_N
        U = [d for d in divisors(N) if d not in (1, N)]
        axes = set(frozenset((d, N // d)) for d in U)
        # представитель каждой оси, НЕ делящийся на новое простое p, = делитель M (≠1)
        p = PRIMES[k - 1]
        reps = set()
        for ax in axes:
            d = min(ax)
            rep = d if d % p != 0 else (N // d)
            reps.add(rep)
        nontrivM = set(d for d in divisors(M) if d != 1)
        bij = (reps == nontrivM) and (len(axes) == len(nontrivM))
        ok_all = ok_all and bij
        print(f"   ранг {k-1}→{k}: M={M}, N={N}: осей N={len(axes)} (расщеплены) ↔ нетрив.делителей M={len(nontrivM)} "
              f"(едины); представители = D(M)\\{{1}}: {bij}")
    check("оси ранга n (κ-пары, деятель↔свидетель РАСЩЕПЛЕНЫ) = нетрив. делители ранга n−1 (ЕДИНЫ) — БИЕКЦИЯ "
          "для n=2..5 ⟹ расщепление наблюдателя = ТЕНЬ единства соседнего ранга", ok_all)


# ═══════════════ D. два вида κ: расщеплена на носителе / снята в факторе ═══════════════
def section_D():
    print("\n[D] ДВА ВИДА κ: на носителе U_n РАСЩЕПЛЕНА (κ-пары), в факторе U_n/κ СНЯТА (единые оси)")
    ok_all = True
    for k in range(2, 6):
        N = squarefree(PRIMES[:k])
        U = [d for d in divisors(N) if d not in (1, N)]
        carrier = len(U)                          # |U_n| = расщеплённые точки
        quotient = len(set(frozenset((d, N // d)) for d in U))   # |U_n/κ| = снятые оси
        ok = (carrier == 2 ** k - 2) and (quotient == 2 ** (k - 1) - 1) and (carrier == 2 * quotient)
        ok_all = ok_all and ok
        print(f"   ранг {k}: носитель |U|={carrier}=2^{k}−2 (расщеплено); фактор |U/κ|={quotient}=2^{{{k-1}}}−1 "
              f"(снято); носитель=2×фактор: {carrier == 2 * quotient}")
    check("на каждом ранге |U_n|=2^n−2 (расщеплено) = 2·|U_n/κ| (фактор, снято) ⟹ κ-симметрия видна ДВОЯКО: "
          "расщеплением на носителе и единством в факторе — наблюдатель=κ, не точка", ok_all)


# ═══════════════ E. страж: числовые мостики санскрита убиты ═══════════════
def section_E():
    print("\n[E] СТРАЖ: '6 караков=октаэдр', '7=Фано' — совпадения по числу, НЕ структура (смена базы убивает)")
    # караков всегда 6 (фикс. грамматич. категория); вершин U_n=2^n−2 (растёт)
    karaka = 6
    coincide_only_at_3 = (2 ** 3 - 2 == karaka) and all(2 ** k - 2 != karaka for k in (4, 5, 6))
    check(f"караков всегда=6; |U_n|=2^n−2 растёт; совпадение |U_n|=6 ТОЛЬКО при n=3 (ранг 4→14≠6): "
          f"{coincide_only_at_3} ⟹ '6 караков=октаэдр' = совпадение по 6 (как 4=2², 8=глюоны), ✗ НЕ берём; "
          f"берём только ЗАЛОГ (parasmaipada↔ātmanepada = κ-пара наружу/внутрь, ● грамматика)", coincide_only_at_3)


def main():
    print("=" * 100)
    print("РАСЩЕПЛЕНИЕ НАБЛЮДАТЕЛЯ (свидетель σ½ / деятель «+1») = проекция κ-симметрии; единство по лифту")
    print("=" * 100)
    section_A(); section_B(); section_C(); section_D(); section_E()
    print("\n" + "=" * 100)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: 'наблюдатель' = НЕ точка σ½, а κ-ИНВАРИАНТНОСТЬ. σ½=√N=отсутствующий центр-СВИДЕТЕЛЬ (вне")
    print("       носителя); деятель «+1»=активная грань (разворачивает ось наружу); κ сшивает (смена залога).")
    print("       κ видна ДВОЯКО: на носителе РАСЩЕПЛЕНА (κ-пары деятель↔свидетель), в факторе U_n/κ СНЯТА")
    print("       (единые оси). ★По закону лифта оси ранга n (расщеплены) = объекты ранга n−1 (едины) —")
    print("       БИЕКЦИЯ ⟹ расщепление = ТЕНЬ единства соседнего ранга; симметрия 'более общего ранга' = κ")
    print("       сама. ● математика; ◐ деятель/свидетель=санскрит; ✗ числовые мостики (6=октаэдр,7=Фано).")
    print("=" * 100)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
