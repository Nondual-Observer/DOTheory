"""
verify_functor_synthesis.py — СШИВКА двух функторизаций: одна машина на ДВУХ сторонах шва |·|₂/|·|∞.

Полная картина = шов прежней функторизации (биты Q_n, теоремо-богатая сторона СТРУКТУРЫ |·|₂: тройка
Λ_L⊣π⊣Λ_R, закон роста PG≅U/κ, монада/терминал, комплекс ∂²=0/Ходж, sl₂=H) и новой (рамка из ι²=id +
числовая сторона ВЫСОТЫ/изнанки |·|∞: ^=кратность v_p, грейдинг P=стрела, двусторонность ∏=1,
μ=обращение). Корень общий (ι²=id); две оси (×/лифт=размерность, exp=угол) = рамка для ОБЕИХ; exp=мост сторон;
∏=1 в двух формах = сам ШОВ в законе. Два слепых пятна зеркальны: биты не видят высоту (^), корневая рамка
проскочила бит-теорему (PG≅U/κ). Шов = каждая сторона несёт найденное другой. Регистр ●◐○: математика (кросс-
модельное единообразие, цепь эманации, ∏=1)=●; «|·|₂/|·|∞↔биты/числа», «exp=мост сторон»=◐; PG-инцидентность
как линейный ВХОД сверх ι²=id честно назван.

  A. ОБЩИЙ КОРЕНЬ ι²=id порождает носитель в ОБЕИХ моделях (κ²=id; орбиты).
  B. ★КРОСС-МОДЕЛЬНОЕ ЕДИНООБРАЗИЕ: морфизмы κ/H/лифт/π совпадают в битах И числах под Λ:S↦∏p.
  C. ЦЕПЬ ЭМАНАЦИИ (сторона |·|₂, из прежней): ι²=id→свободный ℤ/2 (|Hom|=|Y|^{2ⁿ⁻¹})→монада ℤ/2×(−)→терминал σ½.
  D. ГРАНИЦА «ПОСТАВЛЕНО, НЕ ВЫВЕДЕНО»: PG(n−1,2)≅U_{n+1}/κ — счёт 2ⁿ−1 из ι²; ИНЦИДЕНТНОСТЬ=линейный вход.
  E. ДВА СЛЕПЫХ ПЯТНА КАК ФАКТЫ: ^ невидима в битах (бесквадрат=2^k всегда); P различает то, что H(=биты) нет.
  F. ШОВ-ЗАКОН ∏=1 в ДВУХ формах: дискрет Σ(−1)ᵏC(n,k)=0 (биты) = p-адич. ∏_v|x|_v=1 (числа).
  G. ★exp = МОСТ СТОРОН: (+)→(×) счёт→произведение; e^{iπ}=κ (ось угла связывает стороны).
  H. ★СТРАЖ: |·|₂/|·|∞↔биты/числа = узнавание ◐ (не форсировать); PG-вход и слепые пятна названы честно.
"""
from __future__ import annotations
from itertools import product, combinations, permutations
import cmath, math

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok

PRIMES = [2, 3, 5, 7, 11, 13]
def cube(n): return list(product((0, 1), repeat=n))
def kappa_bits(x): return tuple(1 - b for b in x)
def Hw(x): return sum(x)
def divisors(n): return sorted(d for d in range(1, n + 1) if n % d == 0)
def omega(n):
    c, d, p = 0, n, 2
    while p * p <= d:
        if d % p == 0:
            c += 1
            while d % p == 0: d //= p
        p += 1
    if d > 1: c += 1
    return c
def is_squarefree(n):
    d, p = n, 2
    while p * p <= d:
        if d % (p * p) == 0: return False
        if d % p == 0:
            while d % p == 0: d //= p
        p += 1
    return True
def vp(n, p):
    v = 0
    while n % p == 0: n //= p; v += 1
    return v


# ═══════════════ A. общий корень ═══════════════
def section_A():
    print("\n[A] ОБЩИЙ КОРЕНЬ ι²=id порождает носитель в ОБЕИХ моделях (κ²=id; орбиты)")
    bits = all(kappa_bits(kappa_bits(x)) == x for n in (1, 2, 3, 4) for x in cube(n))
    # числа: κ(d)=N/d, κ²=id для бесквадратного N
    nums = True
    for N in (6, 30, 210):
        D = divisors(N)
        nums = nums and all((N // (N // d)) == d for d in D)
    check(f"κ²=id в БИТАХ (Q_n, x↦1−x, ранги 1..4): {bits}; κ²=id в ЧИСЛАХ (D(N), d↦N/d, N=6,30,210): {nums} "
          f"⟹ обе версии стартуют с ОДНОЙ инволюции ι²=id (прежняя на битах, новая поднимает до корня) — "
          f"общий корень есть", bits and nums)


# ═══════════════ B. ★кросс-модельное единообразие ═══════════════
def section_B():
    print("\n[B] ★КРОСС-МОДЕЛЬНОЕ ЕДИНООБРАЗИЕ: морфизмы κ/H/лифт/π совпадают в БИТАХ И ЧИСЛАХ под Λ")
    n = 4
    prs = PRIMES[:n]
    def Lam(S): return math.prod(prs[i] for i in S)           # Λ: подмн.→число (биты→числа)
    full_set = frozenset(range(n))
    subsets = [frozenset(c) for r in range(n + 1) for c in combinations(range(n), r)]
    N = math.prod(prs)
    # κ: дополнение в битах ↔ d↦N/d в числах
    kap = all(Lam(full_set - S) == N // Lam(S) for S in subsets)
    # H: Хэмминг в битах ↔ ω в числах
    Hcoh = all(len(S) == omega(Lam(S)) for S in subsets)
    # лифт Λ_R (добавить ось) в битах ↔ ×новое простое в числах
    n2, prs2 = n + 1, PRIMES[:n + 1]
    def Lam2(S): return math.prod(prs2[i] for i in S)
    liftR = all(Lam2(S | {n}) == Lam(S) * prs2[n] for S in subsets)   # добавить старшую ось = ×p_{n}
    liftL = all(Lam2(S) == Lam(S) for S in subsets)                   # вложить нулём = то же число
    # π: забыть старшую ось ↔ убрать множитель p_n (если есть)
    proj = all((Lam2(S) // (prs2[n] if n in S else 1)) == Lam(S - {n}) for S in subsets)
    check(f"под Λ:S↦∏p ОДИН морфизм = ОДНО в обеих моделях: κ (дополнение ↔ N/d): {kap}; H (Хэмминг ↔ ω): "
          f"{Hcoh}; лифт Λ_R (добавить ось ↔ ×простое): {liftR}, Λ_L (вложить нулём ↔ то же): {liftL}; π "
          f"(забыть ось ↔ убрать множитель): {proj} ⟹ морфизмы машины ЕДИНООБРАЗНЫ ПО МОДЕЛЯМ (биты И числа), "
          f"не только рангам — числа=камертон, подтверждают структуру прежней", kap and Hcoh and liftR and liftL and proj)


# ═══════════════ C. цепь эманации (сторона |·|₂) ═══════════════
def section_C():
    print("\n[C] ЦЕПЬ ЭМАНАЦИИ (сторона |·|₂, из прежней): ι²=id→свободный ℤ/2→монада ℤ/2×(−)→терминал σ½")
    # свободный объект: |Hom_{ℤ/2}(Q_n,Y)|=|Y|^{2^{n-1}} (число орбит κ)
    def orbits(n):
        seen, c = set(), 0
        for x in cube(n):
            if x in seen: continue
            seen.add(x); seen.add(kappa_bits(x)); c += 1
        return c
    free = all(orbits(n) == 2 ** (n - 1) for n in (1, 2, 3, 4))
    # монада T=ℤ/2×(−): η(s)=(0,s), μ(a,b,s)=(a+b,s) mod 2 — 3 закона
    def eta(s): return (0, s)
    def mu(a, b, s): return ((a + b) % 2, s)
    law_unitL = all(mu(0, a, s) == (a, s) for a in (0, 1) for s in range(3))      # μ∘(η×1)=id
    law_assoc = all(mu((a + b) % 2, c, s) == mu(a, (b + c) % 2, s)
                    for a in (0, 1) for b in (0, 1) for c in (0, 1) for s in range(2))
    # терминал σ½: κ=id точка, единств. морфизм Q_n→σ½; в свободных Q_n фикса нет
    no_fix = all(not any(kappa_bits(x) == x for x in cube(n)) for n in (1, 2, 3, 4))
    check(f"свободный ℤ/2-объект |Hom(Q_n,Y)|=|Y|^{{2ⁿ⁻¹}} (#орбит κ=2ⁿ⁻¹): {free}; монада ℤ/2×(−) законы "
          f"(единица: {law_unitL}, ассоц.: {law_assoc}); терминал σ½ — κ-фикса в свободных Q_n НЕТ (κ(x)=x⟹1ⁿ=0): "
          f"{no_fix} ⟹ цепь ι²=id→носитель→монада→терминал РАСТЁТ из корня (эти теоремы прежней рамка "
          f"ВЫВОДИТ, не только ставит)", free and law_unitL and law_assoc and no_fix)


# ═══════════════ D. граница «поставлено, не выведено» ═══════════════
def section_D():
    print("\n[D] ГРАНИЦА: PG(n−1,2)≅U_{n+1}/κ — СЧЁТ 2ⁿ−1 из ι²=id; ИНЦИДЕНТНОСТЬ = ЛИНЕЙНЫЙ вход")
    ok = True
    for n in (2, 3, 4):
        m = n + 1
        U = [x for x in cube(m) if x not in (tuple([0] * m), tuple([1] * m))]
        # κ-пары U_{n+1}
        seen, pairs = set(), []
        for x in U:
            if x in seen: continue
            seen.add(x); seen.add(kappa_bits(x)); pairs.append(x)
        count_ok = (len(pairs) == 2 ** n - 1)   # |U/κ| = 2ⁿ−1 = |PG(n−1,2)|  — СЧЁТ из ι² (орбиты)
        ok = ok and count_ok
    # ИНЦИДЕНТНОСТЬ нужна ЛИНЕЙНАЯ: точки PG(n−1,2)=ненул. векторы 𝔽₂ⁿ, прямая={a,b,a+b} (a+b+c=0).
    # Линейное отображение СОХРАНЯЕТ прямые; произвольная биекция того же множества — НЕТ.
    n = 3
    pts = [v for v in product((0, 1), repeat=n) if any(v)]   # 7 ненул. векторов = PG(2,2)
    def xor(a, b): return tuple(x ^ y for x, y in zip(a, b))
    lines = [frozenset((a, b, xor(a, b))) for a in pts for b in pts if a < b]
    lines = set(l for l in lines if len(l) == 3)
    # тождественная (линейная) биекция сохраняет ВСЕ прямые
    id_keeps = all(xor(a, b) in pts and frozenset((a, b, xor(a, b))) in lines
                   for a in pts for b in pts if a != b)
    # нелинейная перестановка (своп двух координатных векторов с третьим вектором) рвёт хотя бы одну прямую
    e1, e2, e3 = (1, 0, 0), (0, 1, 0), (0, 0, 1)
    swap = {e1: (1, 1, 0), (1, 1, 0): e1}                    # переставить e1 ↔ e1+e2 (нелинейно)
    def perm(v): return swap.get(v, v)
    # прямая {e1,e2,e1+e2}: после perm образ {e1+e2, e2, e1} — это та же прямая (счастливо), берём другую:
    # {e1,e3,e1+e3}=(100,001,101): perm→(110,001,101): сумма 110⊕001⊕101=010≠0 ⟹ НЕ прямая
    broken = (xor(xor(perm(e1), perm(e3)), perm(xor(e1, e3))) != (0, 0, 0))
    check(f"|U_{{n+1}}/κ|=2ⁿ−1=|PG(n−1,2)| (счёт κ-пар = #осей, ранги 2..4): {ok} — это ИЗ ι²=id (орбиты); НО "
          f"инцидентность: линейная биекция хранит прямые ({id_keeps}), нелинейная перестановка РВЁТ прямую "
          f"(e1⊕e3⊕(e1+e3) после свопа ≠0: {broken}) ⟹ PG≅U/κ как ИЗОМОРФИЗМ ПРОЕКТИВНЫХ ПРОСТРАНСТВ нужен "
          f"ЛИНЕЙНЫЙ сдвиг a↦2a — ВХОД сверх ι²=id; рамка его СТАВИТ (живёт в прежней ●), не переоткрывает",
          ok and id_keeps and broken)


# ═══════════════ E. два слепых пятна как факты ═══════════════
def section_E():
    print("\n[E] ДВА СЛЕПЫХ ПЯТНА: ^ невидима в БИТАХ (бесквадрат=2^k); P различает то, что H(=биты-sl₂) нет")
    # (1) биты бесквадратны: D(бесквадратное)=2^k ВСЕГДА; ^ (этаж) даёт НЕ-степень-2 — только в числах
    sf = all(len(divisors(N)) == 2 ** omega(N) for N in (6, 30, 210, 1155))   # бесквадратные=куб
    floor = all((not is_squarefree(N)) and (len(divisors(N)) != 2 ** omega(N)) for N in (12, 18, 4, 8))  # ^ ломает
    # (2) P (позиция) различает 01,10 — H (Хэмминг=sl₂-вес прежней) НЕ различает
    def Pw(x): return sum(b * 2 ** i for i, b in enumerate(reversed(x)))
    P_splits = (Hw((0, 1)) == Hw((1, 0))) and (Pw((0, 1)) != Pw((1, 0)))
    check(f"(1) D(бесквадратное)=2^ω ВСЕГДА (биты=куб, этажей нет): {sf}; ^ даёт |D|≠2^ω (12,18,4,8) — ВЫСОТА "
          f"видна ТОЛЬКО в числах: {floor}; (2) P(позиция) различает 01≠10, H(Хэмминг=sl₂-вес прежней) — НЕТ: "
          f"{P_splits} ⟹ слепые пятна зеркальны: прежняя (биты) не видит ^/изнанку и P; их даёт новая (числа/"
          f"позиция) — шов несёт обе", sf and floor and P_splits)


# ═══════════════ F. шов-закон ∏=1 в двух формах ═══════════════
def section_F():
    print("\n[F] ШОВ-ЗАКОН ∏=1 в ДВУХ формах: дискрет Σ(−1)ᵏC(n,k)=0 (биты) = p-адич. ∏_v|x|_v=1 (числа)")
    disc = all(sum((-1) ** k * math.comb(n, k) for k in range(n + 1)) == 0 for n in (1, 2, 3, 4, 5))
    def prod_formula(num, den):
        val = abs(num / den)
        for p in (2, 3, 5, 7):
            val *= p ** (-(vp(num, p) - vp(den, p)))
        return val
    padic = abs(prod_formula(7, 1) - 1) < 1e-9 and abs(prod_formula(12, 5) - 1) < 1e-9
    check(f"дискрет: Σ_k(−1)ᵏC(n,k)=0 (биты, машинное сохранение, ранги 1..5): {disc}; "
          f"p-адич.: ∏_v|x|_v=1 (числа, 7 и 12/5): {padic} ⟹ ОДНА форма «полный набор→нейтраль» в ОБЕИХ "
          f"моделях — это сам ШОВ |·|₂/|·|∞, поднятый в ЗАКОН (связывает стороны)", disc and padic)


# ═══════════════ G. ★exp = мост сторон ═══════════════
def section_G():
    print("\n[G] ★exp = МОСТ СТОРОН: (+)→(×) счёт→произведение; e^{iπ}=κ (ось угла связывает стороны)")
    homo = all(abs(math.exp(a + b) - math.exp(a) * math.exp(b)) < 1e-9
               for a in (0.3, 1.1) for b in (0.5, 1.7))
    # счёт этажей Ω(N)=Σv_p аддитивен = log-тень умножения (мост сторона счёта→сторона произведения)
    shadow = all(sum(vp(N, p) for p in (2, 3, 5, 7)) == (vp(N, 2) + vp(N, 3) + vp(N, 5) + vp(N, 7))
                 for N in (12, 360, 210))
    kap = abs(cmath.exp(1j * math.pi) - (-1)) < 1e-9
    check(f"exp(a+b)=exp(a)·exp(b) (моноидный изоморфизм +→×, мост стороны СЧЁТА |·|₂ в сторону ПРОИЗВЕДЕНИЯ "
          f"|·|∞): {homo}; Ω=Σv_p аддитивно (log-тень ×): {shadow}; e^{{iπ}}=κ (ось угла): {kap} ⟹ exp = "
          f"единственный мост между двумя сторонами шва (счёт↔произведение, дискрет↔континуум)",
          homo and shadow and kap)


# ═══════════════ H. ★страж ═══════════════
def section_H():
    print("\n[H] ★СТРАЖ: |·|₂/|·|∞↔биты/числа = узнавание ◐ (не форсировать); вход PG и слепые пятна названы")
    # совпадение СТРУКТУР (κ/H/лифт в обеих моделях) — ● (секция B); отождествление СТОРОН шва — ◐
    # страж базы: log база-независим (мост не артефакт основания)
    base_indep = all(abs(math.log(x, b) - math.log(x) / math.log(b)) < 1e-9
                     for x in (5.0, 10.0) for b in (2.0, 7.0))
    print("   ● доказано: общий корень (A), кросс-модельное единообразие (B), эманация монада/терминал (C),")
    print("     слепые пятна как факты (E), ∏=1 в двух формах (F), exp-мост структурно (G, страж базы)")
    print("   ◐ узнавание (НЕ теорема): |·|₂↔биты/структура, |·|∞↔числа/высота; exp=мост СТОРОН (рамка)")
    print("   ○ вход (честно назван): PG≅U/κ инцидентность=линейный вход сверх ι²=id (D); живёт в прежней ●")
    check(f"страж базы (log_b=log/log b, мост базонезависим): {base_indep}; разделено ● (структуры совпали, B) "
          f"vs ◐ (стороны шва=узнавание) vs ○ (PG-инцидентность=вход, D) — сшивка НЕ инфлирует: теоремы прежней "
          f"ПОСТАВЛЕНЫ/часть ВЫВЕДЕНА, отождествление сторон держится ◐", base_indep)


def main():
    print("=" * 100)
    print("СШИВКА ДВУХ ФУНКТОРИЗАЦИЙ: одна машина на ДВУХ сторонах шва |·|₂(структура)/|·|∞(высота); exp=мост; ∏=1=шов")
    print("=" * 100)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_F(); section_G(); section_H()
    print("\n" + "=" * 100)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: ПОЛНАЯ КАРТИНА = шов двух версий. Общий корень ι²=id; две оси (×/лифт=размерность, exp=угол) =")
    print("       рамка ОБЕИХ. Сторона |·|₂ = БИТЫ (прежняя, теоремы: Λ_L⊣π⊣Λ_R, PG≅U/κ, монада/терминал, sl₂=H);")
    print("       сторона |·|∞ = ЧИСЛА (новая: ^=высота, P=стрела, ∏=1, μ). Морфизмы ЕДИНООБРАЗНЫ по моделям (B);")
    print("       монада/терминал ВЫВЕДЕНЫ из корня (C); PG≅U/κ инцидентность ПОСТАВЛЕНА (линейный вход, D, ● в")
    print("       прежней). exp=мост сторон (G); ∏=1 в двух формах=шов-закон (F). Слепые пятна зеркальны (E).")
    print("       ● структуры/эманация/∏=1; ◐ стороны шва↔модели; ○ PG-инцидентность=вход. Сшивка не инфлирует.")
    print("=" * 100)
    return 0 if FAIL == 0 else 1


