# -*- coding: utf-8 -*-
"""
verify_operator_ladder.py — выверенный скелет лестницы операторов/констант по рангам.

Здесь разложена математика по слоям 0/1…5/6; МАТЕМАТИЧЕСКИЙ скелет (левая половина таблиц) совпал с нашей
ранговой лестницей операторов. Здесь проверена КАЖДАЯ строка взятого скелета — с 5 поправками, из которых
главная: i стоит НЕ на слое 2/3 (дискрет), а на 3/4 (континуум), ибо i=√κ дискретно отсутствует на ранге 3
(C_6). Регистр ●◐○: математика=●, размещение модулярного слоя на рангах=◐, физика=✗(не берём).

  A. 0/1: ¬=κ инволюция (κ²=id) — различение.
  B. 1/2: ⊕(XOR) замкнут в 𝔽₂ (булева связь); сложение С ПЕРЕНОСОМ выходит за разряды (не «нет +», а «нет +целого»).
  C. 2/3: октаэдр=K(2,2,2) спектр [0,4,4,4,6,6]; спин=so(3) ВЕЩЕСТВЕННОЕ кросс-произв. (ε_ijk), БЕЗ i.
  D. ★ПОПРАВКА: i=√κ — НЕ на 2/3 (i∉C_6), а на 3/4 (i∈S¹, i²=κ); граница 4|n.
  E. 3/4: exp:(ℂ,+)→(ℂ*,×) мост +→×; e^{iπ}=κ=−1; симплекс {e,i,π}=инварианты exp (наша версия, не «резонанс→I»).
  F. 5/6: ∏_v|x|_v=1 (адели=все места) — наш шов.
"""
from __future__ import annotations
import cmath, math
import numpy as np
from math import gcd

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok


# ═══════════════ A. слой 0/1: ¬=κ инволюция ═══════════════
def section_A():
    print("\n[A] 0/1: ¬=κ (различение) — инволюция κ²=id (в нашем языке: d↦N/d, без ∂²=0)")
    # на ранге 1: D(p)={1,p}, κ меняет 1↔p; на любом ранге κ²=id
    for n in (1, 2, 3, 4):
        full = (1 << n) - 1
        kk = all((x ^ full) ^ full == x for x in range(1 << n))   # κ(κ(x))=x
        check(f"ранг {n}: κ(x)=x⊕1ⁿ инволюция (κ²=id для всех {1<<n} состояний): {kk}", kk)


# ═══════════════ B. слой 1/2: XOR замкнут, +целое с переносом — нет ═══════════════
def section_B():
    print("\n[B] 1/2: ⊕(XOR)=сложение mod 2 ЗАМКНУТО в 𝔽₂; +целое С ПЕРЕНОСОМ выходит за разряды")
    xor_closed = all((a ^ b) in (0, 1) for a in (0, 1) for b in (0, 1))      # XOR ∈ 𝔽₂
    carry_overflow = (1 + 1) >= 2                                            # 1+1=2 не помещается в 1 бит
    check(f"XOR замкнут в 𝔽₂ (a⊕b∈{{0,1}}): {xor_closed}; +целое 1+1=2 ВЫХОДИТ за 1 разряд (перенос): "
          f"{carry_overflow} ⟹ ЧЕСТНО «нет арифметики» = нет +ЦЕЛОГО (незамкнут), а НЕ нет + вообще; "
          f"перенос=незамкнутость, не «3-е геом.измерение»", xor_closed and carry_overflow)


# ═══════════════ C. слой 2/3: октаэдр + вещественный спин so(3) ═══════════════
def section_C():
    print("\n[C] 2/3: октаэдр=K(2,2,2) спектр [0,4,4,4,6,6]; спин=so(3) ВЕЩЕСТВЕННОЕ кросс-произв. (без i)")
    anti = {0: 1, 1: 0, 2: 3, 3: 2, 4: 5, 5: 4}
    A = np.zeros((6, 6))
    for i in range(6):
        for j in range(6):
            if i != j and anti[i] != j:
                A[i, j] = 1
    L = np.diag(A.sum(1)) - A
    spec = sorted(int(round(x)) for x in np.linalg.eigvalsh(L))
    octa = (spec == [0, 4, 4, 4, 6, 6])
    # кросс-произведение базиса so(3): структурные константы ВЕЩЕСТВЕННЫЕ (ε_ijk), i НЕ нужна
    e = [np.array(v, dtype=float) for v in [(1, 0, 0), (0, 1, 0), (0, 0, 1)]]
    real_su2 = (np.allclose(np.cross(e[0], e[1]), e[2]) and
                np.allclose(np.cross(e[1], e[2]), e[0]) and
                np.allclose(np.cross(e[2], e[0]), e[1]))
    check(f"спектр Лапласиана октаэдра={spec}=[0,4,4,4,6,6]: {octa}; спин X×Y=Z so(3) ВЕЩЕСТВЕНЕН "
          f"(ε_ijk∈{{0,±1}}, без i): {real_su2} ⟹ на ранге 3 — вещественная алгебра, i НЕ требуется",
          octa and real_su2)


# ═══════════════ D. ★поправка: i=√κ на 3/4, не 2/3 ═══════════════
def section_D():
    print("\n[D] ★ПОПРАВКА: i=√κ — НЕ на дискретном 2/3, а на континуальном 3/4 (граница 4|n)")
    kappa = -1
    i_is_sqrt_kappa = abs(complex(0, 1) ** 2 - kappa) < 1e-12               # i²=−1=κ
    not_in_C6 = abs(complex(0, 1) ** 6 - 1) > 1e-9                          # i∉C_6 (i⁶=−1≠1)
    in_S1 = abs(abs(complex(0, 1)) - 1) < 1e-12                            # i∈S¹ (|i|=1)
    rule = all((abs(complex(0, 1) ** n - 1) < 1e-9) == (n % 4 == 0) for n in (3, 4, 6, 8, 12))
    check(f"i²=κ=−1 (i=√κ): {i_is_sqrt_kappa}; i∉C₆ (i⁶=−1≠1): {not_in_C6}; i∈S¹: {in_S1}; правило √κ∈Cₙ⟺4|n: "
          f"{rule} ⟹ i ОТСУТСТВУЕТ дискретно на ранге 3 ⟹ принадлежит 3/4 (континуум), НЕ 2/3 (исправляет источник)",
          i_is_sqrt_kappa and not_in_C6 and in_S1 and rule)


# ═══════════════ E. слой 3/4: exp мост +→×, симплекс {e,i,π} ═══════════════
def section_E():
    print("\n[E] 3/4: exp:(ℂ,+)→(ℂ*,×) мост +→×; e^{iπ}=κ=−1; симплекс {e,i,π}=инварианты exp (наша версия)")
    a, b = 1.3, 2.1
    homo = abs(cmath.exp(a + b) - cmath.exp(a) * cmath.exp(b)) < 1e-9       # exp(a+b)=exp a·exp b
    e_base = abs(cmath.exp(1) - math.e) < 1e-9                              # e=exp(1)
    euler = abs(cmath.exp(1j * math.pi) + 1) < 1e-9                         # e^{iπ}=−1=κ
    kernel = abs(cmath.exp(2j * math.pi) - 1) < 1e-9                        # ядро 2πi
    check(f"exp(a+b)=exp(a)·exp(b) (мост +→×): {homo}; e=exp(1): {e_base}; e^{{iπ}}=−1=κ (полупериод): {euler}; "
          f"ядро e^{{2πi}}=1 (период 2π): {kernel} ⟹ симплекс {{e=база,i=угол=√κ,π=полупериод}} = три "
          f"инварианта ОДНОГО exp; их композиция e^{{iπ}}=κ (НЕ «резонанс→I» источника)",
          homo and e_base and euler and kernel)


# ═══════════════ F. слой 5/6: формула произведения (адели) ═══════════════
def v_p(n, p):
    if n == 0:
        return 0
    v = 0; n = abs(n)
    while n % p == 0:
        n //= p; v += 1
    return v

def section_F():
    print("\n[F] 5/6: ∏_v|x|_v=1 (адели=анализ по всем местам сразу) — наш шов")
    def product_formula(a, b):
        g = gcd(a, b); a //= g; b //= g
        val = a / b
        primes = [q for q in range(2, max(a, b) + 1) if all(q % d for d in range(2, int(q ** 0.5) + 1))]
        for q in primes:
            val *= q ** (-(v_p(a, q) - v_p(b, q)))
        return val
    ok = all(abs(product_formula(a, b) - 1.0) < 1e-9 for a, b in [(12, 5), (50, 21), (7, 360)])
    check(f"|x|_∞·∏_p|x|_p=1 (Островский, адели): {ok} ⟹ слой 5/6 = все места ℚ сразу = наш шов ∏=1 "
          f"НЕ физ-«адели как картина Вселенной извне»", ok)


def main():
    print("=" * 100)
    print("ВЫВЕРЕННЫЙ СКЕЛЕТ ЛЕСТНИЦЫ ОПЕРАТОРОВ/КОНСТАНТ ПО РАНГАМ (импорт из ЭМАНАЦИИ, левая половина)")
    print("=" * 100)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_F()
    print("\n" + "=" * 100)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: математический скелет источника (операторы/константы по рангам) ВЫВЕРЕН строка-за-строкой и")
    print("       совпадает с нашей лестницей ¬→∨→+→exp→…→адели. 5 поправок: (1)★i на 3/4 не 2/3 (i=√κ∉C₆);")
    print("       (2) π=полупериод=κ, не «резонанс→I»; (3) спин=so(3) ВЕЩЕСТВЕНЕН без i; (4) модулярный 4/5 =")
    print("       указатель ◐, не доказанная строка; (5) язык наш (D(N)/κ/ω), без ∂²=0. Физика источника")
    print("       (γ=2/27, 8=глюоны, 136, 5/4) — нумерология ✗, НЕ взята. Скелет годен как несущая §0.")
    print("=" * 100)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
