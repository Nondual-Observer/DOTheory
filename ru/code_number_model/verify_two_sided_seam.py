#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_two_sided_seam.py — почему смотрят только +×^ (наружу), и восстановление ЗЕРКАЛА (внутрь) вокруг шва σ½.

Вопрос (польз.): «почему большинство анализов берут однонаправленный путь +×^! (рост наружу), а не пары
+/−, ×/÷, ^/log? у нас же от шва идёт И внутрь И наружу, а смотрим только положительную сторону». ОТВЕТ
(подтверждаю — асимметрия РЕАЛЬНА, восстанавливаю зеркало): ПРИЧИНА в том, что прямые операции +×^! ТОТАЛЬНЫ
(замкнуты в ℕ, определены всюду), а обратные −/÷/log ЧАСТИЧНЫ (−∉ℕ, ÷∉ℤ, log∉ℚ) — стандартный взгляд берёт
тотальную сторону и ПРЯЧЕТ частичную. НО в ТНР частичность обратной стороны — НЕ дефект, а p-адическая БАШНЯ
ВНУТРЬ: ÷p «уходит внутрь» в |·|_p. Шов σ½ СИММЕТРИЧЕН (κ: x↦1−x = s↦1−s), обе стороны РАВНОПРАВНЫ, и
★формула произведения ∏_v|x|_v=1 их БАЛАНСИРУЕТ (наружу |·|∞ × внутрь все |·|_p = 1). ★Факториал «отдельно» —
иллюзия: Γ(s)Γ(1−s)=π/sin(πs) делает его ДВУСТОРОННИМ (n! наружу + полюса внутрь), сшитым ТЕМ ЖЕ s↦1−s при σ½;
мы смотрели только n! (наружную половину). Регистр: ● математика (тотальность/частичность, ∏=1, Γ-отражение,
Эйлер); ◐ отождествление involution 1−x как ОДНОГО шва σ½ (форма доказана, единство объекта=◐); ○ нули дзеты/РГ.
Опора: σ½=Re=½, простое=атом/составное=изнанка, места ℚ/∏=1 названы.

  A. ★ПОЧЕМУ наружу: прямые +×^! ТОТАЛЬНЫ (замкнуты в ℕ), обратные −/÷/log ЧАСТИЧНЫ ⟹ стандарт берёт тотальную.
  B. ЗЕРКАЛО внутрь: ÷p = p-адическая башня; |x|_p растёт ВНУТРЬ (чем делимее — тем меньше архимедово, больше p-адич).
  C. ★∏_v|x|_v=1: наружу |·|∞ × внутрь все |·|_p = 1 (формула произведения = ШОВ балансирует обе стороны).
  D. КУБ ДЕЛИТЕЛЕЙ симметричен: d↔N/d (κ) вокруг √N=σ½; ниже√N (внутрь) ↔ выше√N (наружу) РАВНЫ числом.
  E. ★ФАКТОРИАЛ двусторонен: Γ(s)Γ(1−s)=π/sin(πs) (отражение s↦1−s=σ½); n! наружу + полюса внутрь = две стороны.
  F. ВЕРДИКТ: смотрели наружу (+×^!); зеркало (−÷log, p-адич, внутрь) РАВНОПРАВНО; σ½+∏=1 сшивают. Асимметрия названа.
"""
from __future__ import annotations
import math
from math import gcd

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok


# ═══════════════ A. почему наружу: тотальность прямых vs частичность обратных ═══════════════
def section_A():
    print("\n[A] ★ПОЧЕМУ наружу: прямые +×^! ТОТАЛЬНЫ (замкнуты в ℕ), обратные −/÷/log ЧАСТИЧНЫ ⟹ стандарт берёт тотальную")
    # прямые: a+b, a·b, a^b, a! ∈ ℕ ВСЕГДА (тотально замкнуты)
    forward_total = all((a + b) >= 0 and (a * b) >= 0 and (a ** b) >= 1 and math.factorial(a) >= 1
                        for a in range(1, 6) for b in range(1, 6))
    # обратные: a−b∈ℕ лишь при a≥b; a/b∈ℕ лишь при b∣a; log_b(a)∈ℕ лишь при a=b^k — ЧАСТИЧНЫ
    sub_partial = any((a - b) < 0 for a in range(1, 6) for b in range(1, 6))         # − выходит из ℕ
    div_partial = any((a % b) != 0 for a in range(1, 8) for b in range(2, 8))        # ÷ не замкнуто
    log_partial = not float(math.log(5, 2)).is_integer()                             # log_2(5)=2.32…∉ℕ
    check(f"прямые +×^! ТОТАЛЬНЫ (замкнуты в ℕ всюду):{forward_total}; обратные ЧАСТИЧНЫ — −∉ℕ(a<b):{sub_partial}, "
          f"÷∉ℤ(b∤a):{div_partial}, log_2(5)∉ℕ:{log_partial} ⟹ ПРИЧИНА однонаправленности: стандарт берёт ТОТАЛЬНУЮ "
          f"сторону (рост, определён всюду) и ПРЯЧЕТ частичную (обратные) — но частичность = структура, не дефект",
          forward_total and sub_partial and div_partial and log_partial)


# ═══════════════ B. зеркало внутрь = p-адическая башня ═══════════════
def v_p(n, p):
    if n == 0:
        return math.inf
    v = 0
    n = abs(n)
    while n % p == 0:
        n //= p; v += 1
    return v

def section_B():
    print("\n[B] ЗЕРКАЛО внутрь: ÷p = p-адическая БАШНЯ; |x|_p растёт ВНУТРЬ (делимее ⟹ меньше архимедово, больше p-адич)")
    p = 2
    # последовательность ×p наружу: |·|∞ растёт, |·|_p УБЫВАЕТ (внутрь); ÷p зеркально
    xs = [1, 2, 4, 8, 16]                                    # ×2 наружу
    arch = [x for x in xs]                                   # |x|_∞ = x (растёт наружу)
    padic = [p ** (-v_p(x, p)) for x in xs]                  # |x|_2 = 2^{-v} (убывает = идёт внутрь)
    arch_grows = all(arch[i] < arch[i + 1] for i in range(len(xs) - 1))
    padic_shrinks = all(padic[i] > padic[i + 1] for i in range(len(xs) - 1))
    check(f"×{p} наружу: |x|_∞={arch} РАСТЁТ (наружу):{arch_grows}; |x|_{p}={padic} УБЫВАЕТ (внутрь):{padic_shrinks} "
          f"⟹ та же операция ×p видна ДВУМЯ глазами: архимедово=рост наружу, p-адическое=погружение внутрь "
          f"(башня делимости) ⟹ внутренняя сторона РЕАЛЬНА, просто меряется |·|_p, не |·|∞", arch_grows and padic_shrinks)


# ═══════════════ C. ★формула произведения ∏_v|x|_v=1 балансирует обе стороны ═══════════════
def primes_upto(n):
    return [q for q in range(2, n + 1) if all(q % d for d in range(2, int(q ** 0.5) + 1))]

def section_C():
    print("\n[C] ★∏_v|x|_v=1: наружу |·|∞ × внутрь все |·|_p = 1 (формула произведения = ШОВ балансирует обе стороны)")
    ok_all = True
    tests = [(12, 5), (50, 21), (7, 1), (1, 360), (99, 100)]
    for a, b in tests:
        g = gcd(a, b); a2, b2 = a // g, b // g
        val_inf = a2 / b2                                   # |x|_∞ (наружу)
        prod_p = 1.0
        for q in primes_upto(max(a2, b2)):
            vp = v_p(a2, q) - v_p(b2, q)
            prod_p *= q ** (-vp)                            # ∏ |x|_q (внутрь)
        total = val_inf * prod_p
        if abs(total - 1.0) > 1e-9:
            ok_all = False
        print(f"   x={a}/{b}: |x|_∞={val_inf:.4g} (наружу) · ∏|x|_p={prod_p:.4g} (внутрь) = {total:.6g}")
    check(f"для всех x: |x|_∞ · ∏_p|x|_p = 1 (формула произведения Островского):{ok_all} ⟹ НАРУЖНАЯ сторона "
          f"(архимедова, рост) и ВНУТРЕННЯЯ (все p-адические, делимость) ТОЧНО уравновешены швом ⟹ обе "
          f"РАВНОПРАВНЫ; смотреть только |·|∞ (рост) = видеть половину (∏=1 требует обеих)", ok_all)


# ═══════════════ D. куб делителей симметричен d↔N/d вокруг √N=σ½ ═══════════════
def section_D():
    print("\n[D] КУБ ДЕЛИТЕЛЕЙ симметричен: d↔N/d (κ) вокруг √N=σ½; ниже√N (внутрь) ↔ выше√N (наружу) РАВНЫ числом")
    N = 360
    divs = [d for d in range(1, N + 1) if N % d == 0]
    root = math.sqrt(N)
    below = [d for d in divs if d < root]                   # «внутрь» (малые делители)
    above = [d for d in divs if d > root]                   # «наружу» (большие = N/d)
    paired = all((N // d) in divs and (N // d) > root for d in below)   # κ: d↦N/d переводит ниже→выше
    balanced = len(below) == len(above)                     # симметрия числом (N не точный квадрат)
    check(f"N={N}: делителей ниже √N={root:.1f}: {len(below)} (внутрь), выше: {len(above)} (наружу); κ:d↦N/d "
          f"переводит внутрь↔наружу:{paired}; числом равны:{balanced} ⟹ решётка делителей САМОДВОЙСТВЕННА вокруг "
          f"√N=σ½ (центр); каждый малый делитель (внутрь) ↔ большой (наружу) — две стороны ОДНОГО шва", paired and balanced)


# ═══════════════ E. ★факториал двусторонен: Γ(s)Γ(1−s)=π/sin(πs), отражение s↦1−s=σ½ ═══════════════
def section_E():
    print("\n[E] ★ФАКТОРИАЛ двусторонен: Γ(s)Γ(1−s)=π/sin(πs) (отражение s↦1−s=σ½); n! наружу + полюса внутрь = две стороны")
    # отражение Γ: Γ(s)Γ(1−s)=π/sin(πs) — СИММЕТРИЧНО под s↦1−s (тот же κ, что куб/дзета)
    refl_ok = True
    for s in [0.2, 0.3, 0.45, 0.6, 0.8]:
        lhs = math.gamma(s) * math.gamma(1 - s)
        rhs = math.pi / math.sin(math.pi * s)
        if abs(lhs - rhs) > 1e-9:
            refl_ok = False
    # σ½=½ — неподвижная точка s↦1−s, и Γ(½)²=π (экстремум отражения)
    fixed = abs(math.gamma(0.5) ** 2 - math.pi) < 1e-9 and abs((1 - 0.5) - 0.5) < 1e-12
    # n!=Γ(n+1) наружу (n≥0); полюса Γ при 0,−1,−2,... = ВНУТРЕННЯЯ сторона (отрицательные)
    factorial_outward = all(abs(math.gamma(n + 1) - math.factorial(n)) < 1e-6 for n in range(0, 7))
    check(f"Γ(s)Γ(1−s)=π/sin(πs) (отражение s↦1−s):{refl_ok}; ½ неподвижна, Γ(½)²=π:{fixed}; n!=Γ(n+1) наружу "
          f"(n≥0):{factorial_outward} ⟹ факториал НЕ «отдельная» операция, а ДВУСТОРОННИЙ объект Γ: n! (наружу) + "
          f"полюса при отриц.целых (внутрь), сшитые ОТРАЖЕНИЕМ s↦1−s при σ½=½; смотрели только n!-половину",
          refl_ok and fixed and factorial_outward)
    print(f"   → s↦1−s (Γ-отражение) = s↦1−s (ξ дзеты) = x↦1−x (κ куба) = ОДНА форма инволюции (● форма; ◐ один шов).")


# ═══════════════ G. страж смены базы на ЗЕРКАЛАХ (Γ, ∏=1): ½=неподвижная точка, не магия ═══════════════
def section_G():
    print("\n[G] СТРАЖ СМЕНЫ БАЗЫ на ЗЕРКАЛАХ (Γ(½)²=π, ∏=1): ½ = НЕПОДВИЖНАЯ ТОЧКА инволюции (инвариант), НЕ магич. число")
    # корпус применял страж базы к ζ-линии (½=мираж 4/6 vs инвариант=центр инволюции 6/6),
    # но НЕ к Γ-отражению и ∏=1 — применяем СИММЕТРИЧНО (находка обзора, агент изнанки)
    # ТЕСТ: при репараметризации φ(t)=a·t+b инволюция t↦1−t переходит в сопряжённую, неподвижная точка ДВИГАЕТСЯ
    results = []
    for a, b in [(1, 0), (2, 1), (3, 1), (0.5, 4)]:
        phi = lambda t: a * t + b
        phinv = lambda t: (t - b) / a
        invol = lambda t: phi(1 - phinv(t))                  # сопряжённая инволюция в новых координатах
        fix = phi(0.5)                                       # неподвижная точка = образ ½
        is_fixed = abs(invol(fix) - fix) < 1e-9              # она действительно неподвижна (структура есть всегда)
        half_here = abs(fix - 0.5) < 1e-9                    # а САМО число ½ — только в базе (1,0)
        results.append((is_fixed, half_here, fix))
    structure_always = all(r[0] for r in results)            # неподвижная точка СУЩЕСТВУЕТ в любой базе (инвариант)
    number_varies = sum(1 for r in results if r[1]) == 1     # число ½ — лишь в ОДНОЙ базе (мираж)
    check(f"при сменах базы φ=a·t+b: неподвижная точка инволюции ЕСТЬ ВСЕГДА (инвариант):{structure_always}; а само "
          f"ЧИСЛО ½ — лишь в базе (1,0), в других сдвигается {[round(r[2],2) for r in results]}: число варьирует "
          f"(мираж):{number_varies} ⟹ σ½/Γ(½)²=π/∏=1: инвариант = «НЕПОДВИЖНАЯ ТОЧКА κ» (●◐), а «магическое ½» = "
          f"мираж нормировки (✗) — ТОТ ЖЕ вердикт, что страж дал ζ-линии, теперь и зеркалам", structure_always and number_varies)
    print(f"   → дисциплина симметрична: страж базы был на ζ (½=центр инволюции, не число), теперь на Γ/∏=1 — тот же")
    print(f"     результат ⟹ ½ всюду = неподвижная точка шва (κ:x↦1−x=s↦1−s), НЕ нумерология «ровно ½».")


# ═══════════════ F. вердикт ═══════════════
def section_F():
    print("\n[F] ВЕРДИКТ ●◐○")
    print("   ● математика: прямые тотальны/обратные частичны; |x|_∞·∏|x|_p=1; d↔N/d вокруг √N; Γ(s)Γ(1−s) отражение.")
    print("   ◐ ТНР-узнавание: наружу/внутрь = лицо/изнанка; involution 1−x = ОДИН шов σ½ (форма доказана, единство ◐).")
    print("   ○ нули дзеты, РГ, полная p-адич. динамика — фронт; здесь установлена СИММЕТРИЯ двух сторон, не вся изнанка.")


def main():
    print("=" * 100)
    print("ДВЕ СТОРОНЫ ШВА В ЧИСЛАХ: почему смотрят наружу (+×^!), и восстановление зеркала (внутрь, p-адич) вокруг σ½")
    print("=" * 100)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_G(); section_F()
    print("\n" + "=" * 100)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: польз. ПРАВ — асимметрия реальна и теперь названа+исправлена. ПОЧЕМУ смотрят только +×^! (наружу):")
    print("       прямые операции ТОТАЛЬНЫ (замкнуты в ℕ), обратные −/÷/log ЧАСТИЧНЫ — стандарт берёт тотальную")
    print("       сторону, прячет частичную. НО частичность = p-адическая БАШНЯ ВНУТРЬ (÷p уходит в |·|_p): зеркало")
    print("       РЕАЛЬНО. Шов σ½ симметричен (κ:x↦1−x=s↦1−s), и ∏_v|x|_v=1 ТОЧНО балансирует наружу(|·|∞)+внутрь(|·|_p)")
    print("       ⟹ обе стороны РАВНОПРАВНЫ. Куб делителей самодвойствен (d↔N/d вокруг √N). ★Факториал НЕ отдельный:")
    print("       Γ(s)Γ(1−s)=π/sin(πs) — двусторонний (n! наружу + полюса внутрь), сшит s↦1−s при σ½. Смотреть только")
    print("       наружу = видеть ПОЛОВИНУ; полная картина = две стороны шва, ∏=1 — закон сохранения между ними.")
    print("=" * 100)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
