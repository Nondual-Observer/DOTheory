#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_number_row.py — НАТУРАЛЬНЫЙ РЯД через ТНР (часть B): счёт=движение, простое=атом, D(N)≅Q_n, Эйлер.

Запрос: натуральный ряд = дискретное движение по непрерывной границе (1+1, аддитивное); простое = инвариант
счёта БЕЗ внутреннего содержания; составное = обратная сторона (состав простых); D(N)≅Q_n; тот же
шов/Риман что физика (часть A); Эйлер/дзета. Как называется — теория чисел. Параллель части A (Physics_Chain).

Дисциплина: каждый check ФАЛЬСИФИЦИРУЕМ (рядом — различающий контроль). Значения=вход(○).

  A. НАТУРАЛЬНЫЙ РЯД = АДДИТИВНОЕ ДВИЖЕНИЕ (+1), ОТЛИЧНОЕ от мультипликативного (×2): аддит. орбита +1 из 0
     покрывает ВЕСЬ ряд, мультипл. орбита ×2 из 1 разрежена {1,2,4,8,…} (различающий: орбиты не совпадают).
  B. ПРОСТОЕ = АТОМ СЧЁТА (без состава): prime ⟺ ровно 2 делителя {1,p}; составное ⟺ >2 (есть состав).
     Различающий: простые дают |D|=2, составные >2 (а 1 — единица, |D|=1, не атом и не состав).
  C. ★D(N) ≅ Q_k для squarefree N=p₁···p_k: решётка делителей ИЗОМОРФНА булеву кубу (делитель↔подмножество
     простых, делимость↔⊆). Различающий: N с квадратом (p²) НЕ булев куб (|D| не степень 2, цепь).
  D. ЭЙЛЕР сшивает СЧЁТ и ПРОСТЫЕ: ζ(s)=Σ_n n^−s = ∏_p (1−p^−s)^−1 (s=2 → π²/6). Сумма по натуральным =
     произведение по простым ⟺ единственность разложения. Различающий: ∏ по СОСТАВНЫМ ≠ ζ (двойной счёт).
  E. σ½ = ОБЩИЙ ШОВ физики и чисел: функц. уравнение ζ(s)↔ζ(1−s) симметрично относит. Re=½ (=σ½ части A).
     Различающий: вне Re=½ нет неподвижности s↦1−s. Тот же центр, что центральная ось физики.
  F. ФУНКТОРНЫЙ ЗАКОН (категорификация, FinSet): +/×/^ = ⊔/×/exp; n^m=|Hom(m,n)|; |Q_n|=2^n=|2^[n]|.
     Различающий: ^ несимметрично (n^m≠m^n) как Hom; × симметрично.
"""
from __future__ import annotations
from itertools import combinations
import numpy as np

PASS = 0; FAIL = 0
def check(name, cond, extra=""):
    global PASS, FAIL
    ok = bool(cond)
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f"   {extra}" if extra and not ok else ""))
    PASS += ok; FAIL += (not ok)
    return ok


# ═══════ A. натуральный ряд = аддитивное движение (≠ мультипликативного) ═══════
def section_A():
    print("\n[A] НАТУРАЛЬНЫЙ РЯД = АДДИТИВНОЕ ДВИЖЕНИЕ (+1), ОТЛИЧНОЕ от мультипликативного (×2)")
    M = 33
    # аддитивная орбита 0 под +1 покрывает ВЕСЬ ряд; мультипликативная орбита 1 под ×2 — разрежена
    add_orbit, n = set(), 0
    while n < M: add_orbit.add(n); n += 1
    mul_orbit, m = set(), 1
    while m < M: mul_orbit.add(m); m *= 2
    # различающий: если бы ряд был «мультипликативным», +1 не покрыл бы всё / орбиты совпали бы
    check("аддитивная орбита (+1) из 0 = ВЕСЬ ряд [0,M): succ порождает ℕ — натуральный ряд = движение +",
          add_orbit == set(range(M)))
    check("мультипликативная орбита (×2) из 1 = РАЗРЕЖЕНА {1,2,4,8,16,32} ⊊ ряд — ИНОЕ движение (× ≠ +)",
          mul_orbit == {1, 2, 4, 8, 16, 32} and mul_orbit < add_orbit)
    print("   → ряд = аддитивный путь +1 (дискрет шаг по непрер. мере |·|∞(n)=n); ×=разрастание, ^=предел")
    print("     = три движения +/×/^ (как у времени)")


# ═══════ B. простое = атом счёта ═══════
def section_B():
    print("\n[B] ПРОСТОЕ = АТОМ СЧЁТА (без внутреннего состава); составное = обратная сторона (состав)")
    def divisors(n):
        return [d for d in range(1, n + 1) if n % d == 0]
    primes = [p for p in range(2, 40) if len(divisors(p)) == 2]
    comps = [c for c in range(2, 40) if len(divisors(c)) > 2]
    # различающий: простое ⟺ |D|=2 (атом, нет состава); составное ⟺ |D|>2 (есть состав); 1 ⟺ |D|=1 (единица)
    primes_are_atoms = all(len(divisors(p)) == 2 for p in primes) and primes[:5] == [2, 3, 5, 7, 11]
    comps_have_structure = all(len(divisors(c)) > 2 for c in comps) and 1 not in comps and 1 not in primes
    one_is_unit = len(divisors(1)) == 1
    check("простое = АТОМ: ровно 2 делителя {1,p} (нет внутреннего состава) — инвариант счёта", primes_are_atoms)
    check("составное = ОБРАТНАЯ сторона: >2 делителей (состав из простых); 1 = единица (|D|=1, ни атом, ни состав)",
          comps_have_structure and one_is_unit)


# ═══════ C. D(N) ≅ Q_k ═══════
def section_C():
    print("\n[C] ★D(N) ≅ Q_k для squarefree N=p₁···p_k: решётка делителей = булев куб (делитель↔подмножество)")
    primes = [2, 3, 5]                                       # k=3 → ожидаем Q₃
    N = 2 * 3 * 5
    divs = sorted(d for d in range(1, N + 1) if N % d == 0)
    # подмножества простых → делители; делимость d1|d2 ⟺ S1⊆S2 (изоморфизм порядков D(N)≅(2^[k],⊆))
    subsets = [frozenset(c) for r in range(len(primes) + 1) for c in combinations(range(len(primes)), r)]
    prod = lambda S: int(np.prod([primes[i] for i in S])) if S else 1
    sub_to_div = {S: prod(S) for S in subsets}
    # матрица делимости делителей и матрица включения подмножеств должны совпасть под этим соответствием
    order_iso = True
    for S1 in subsets:
        for S2 in subsets:
            divides = (sub_to_div[S2] % sub_to_div[S1] == 0)
            included = S1 <= S2
            if divides != included:
                order_iso = False
    cube_size = (len(divs) == 2 ** len(primes))             # |D(N)|=2^k = |Q_k|
    check(f"D({N})≅Q_{len(primes)}: |D|={len(divs)}=2^{len(primes)} и делимость ⟺ ⊆ (изоморфизм решётки кубу)",
          order_iso and cube_size)
    # различающий контроль: N=12=2²·3 НЕ squarefree ⟹ НЕ булев куб (|D|=6 не степень 2)
    d12 = [d for d in range(1, 13) if 12 % d == 0]
    not_cube = (len(d12) != 2 ** int(round(np.log2(len(d12)))))  # 6 не степень двойки
    check("различающий: N=12=2²·3 (с квадратом) НЕ куб — |D(12)|=6 не степень 2 ⟹ нужен squarefree", not_cube)
    print("   → число без квадратов = булев куб его простых (D(p₁p₂p₃)=Q₃); состав = подмножество атомов")


# ═══════ D. Эйлер сшивает счёт и простые ═══════
def section_D():
    print("\n[D] ЭЙЛЕР: ζ(s)=Σ_n n^−s = ∏_p (1−p^−s)^−1 — сумма по СЧЁТУ = произведение по ПРОСТЫМ")
    s = 2.0
    target = np.pi ** 2 / 6                                  # ζ(2)
    Nmax, Pmax = 20000, 20000
    zeta_sum = sum(n ** (-s) for n in range(1, Nmax + 1))
    primes = [p for p in range(2, Pmax + 1) if all(p % q for q in range(2, int(p ** 0.5) + 1))]
    euler_prod = 1.0
    for p in primes:
        euler_prod *= 1.0 / (1.0 - p ** (-s))
    # сумма по натуральным ≈ произведение по простым ≈ π²/6 (единственность разложения, осн.т.арифметики)
    agree = abs(zeta_sum - target) < 1e-3 and abs(euler_prod - target) < 1e-3
    check("ζ(2)=Σn^−2 = ∏_p(1−p^−2)^−1 = π²/6: счёт всех чисел = произведение атомов (единственность разложения)",
          agree, f"sum={zeta_sum:.6f} prod={euler_prod:.6f} π²/6={target:.6f}")
    # различающий: произведение по СОСТАВНЫМ ≠ ζ (двойной учёт простых) — атомарность простых необходима
    comps = [c for c in range(4, 200) if any(c % q == 0 for q in range(2, c))]
    prod_comp = 1.0
    for c in comps:
        prod_comp *= 1.0 / (1.0 - c ** (-s))
    differs = abs(prod_comp - target) > 0.1
    check("различающий: ∏ по СОСТАВНЫМ ≠ ζ(2) (двойной учёт) ⟹ произведение идёт ТОЛЬКО по атомам-простых",
          differs)


# ═══════ E. σ½ = общий шов физики и чисел ═══════
def section_E():
    print("\n[E] σ½ = ОБЩИЙ ШОВ: ζ(s)↔ζ(1−s) симметрично относит. Re=½ (= центральная ось физики, часть A)")
    # функциональное уравнение симметрично относит. s↦1−s; неподвижная линия Re=½ (тот же σ½)
    on, off = 0.5 + 14.13j, 0.7 + 14.13j                    # 0.5+14.13i ~ первый нетрив. ноль
    re_half_fixed = abs((1 - on).real - on.real) < 1e-12
    off_not_fixed = abs((1 - off).real - off.real) > 1e-9   # различающий: вне Re=½ не неподвижна
    check("Re(s)=½ = неподвижная s↦1−s (ось симметрии функц.уравнения ζ); вне — нет. = σ½ физики [◐ отождествл.]",
          re_half_fixed and off_not_fixed)
    print("   → ● строго: инволюция t↦1−t (и на кубе [0,1]ⁿ, и на ℂ) неподвижна на Re=½. [◐] что это ОДИН шов")
    print("     физики и чисел — узнавание по ОБЩЕЙ алгебр. форме 1−x, не доказательство (дзета/горизонты не тронуты)")


# ═══════ F. функторный закон (категорификация) ═══════
def section_F():
    from itertools import product
    print("\n[F] ФУНКТОРНЫЙ ЗАКОН (категорификация FinSet): +/×/^ = ⊔/×/exp; n^m=|Hom(m,n)|; |Q_n|=2^n")
    # СТРОИМ объекты и считаем (не формула против себя): |функций m→n| и |подмножеств [n]|
    hom_counts = {(n, m): len(list(product(range(n), repeat=m))) for n in range(1, 4) for m in range(1, 4)}
    pow_is_hom = all(hom_counts[(n, m)] == n ** m for n in range(1, 4) for m in range(1, 4))
    cube_is_subsets = all(len(list(product((0, 1), repeat=n))) == 2 ** n for n in range(6))  # 2^[n]
    # содержательно: ^ НЕсимметрично (n^m≠m^n в общем) как Hom несимметричен; × симметрично (различающий)
    pow_asym = any(n ** m != m ** n for n in range(1, 5) for m in range(1, 5))
    mul_sym = all(n * m == m * n for n in range(1, 5) for m in range(1, 5))
    check("n^m = |Hom(m,n)| (построил функции m→n, посчитал); |Q_n|=2^n=|подмножеств [n]| (построил, посчитал)",
          pow_is_hom and cube_is_subsets)
    check("различающий: ^ НЕсимметрично (∃ n^m≠m^n) как Hom; × симметрично (n·m=m·n) — категорификация +/×/^",
          pow_asym and mul_sym)
    print("   → закон натурального ряда уже функторен (Lawvere–Schanuel/Baez): числа=скелет FinSet; ТНР")
    print("     добавляет НАБЛЮДАТЕЛЯ σ½ + шов мест |·|₂/|·|∞ (чего нет в чистой категорификации) — см. док §6")


def main():
    print("=" * 96)
    print("НАТУРАЛЬНЫЙ РЯД через ТНР (часть B): счёт=движение · простое=атом · D(N)≅Q_k · Эйлер · σ½-шов")
    print("=" * 96)
    section_A(); section_B(); section_C(); section_D(); section_E(); section_F()
    print("\n" + "=" * 96)
    print(f"ИТОГ: {PASS} PASS / {FAIL} FAIL")
    print("ВЫВОД: натуральный ряд = аддитивное движение (succ +1, дискрет по непрер. мере). Простое = АТОМ")
    print("       счёта (2 делителя, без состава); составное = обратная сторона (подмножество атомов). ★D(N)≅")
    print("       Q_k для squarefree (решётка делителей = булев куб простых). Эйлер ζ=Σ_n=∏_p сшивает счёт и")
    print("       простые (единственность разложения). σ½=Re=½ = ОБЩИЙ шов физики (часть A) и чисел. Закон")
    print("       ряда уже функторен (FinSet, Lawvere); вклад ТНР = наблюдатель σ½ + шов мест. Значения=вход(○).")
    print("=" * 96)
    return 0 if FAIL == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
