# -*- coding: utf-8 -*-
"""
verify_rank5_masses.py — ЧЕСТНЫЙ тест «ранг 5 (золото φ) → иерархия масс».
Считаем реальные данные (PDG), не подгоняем. Дисциплина: φ-золото≈1.618 ≠ фаза 2/9.
"""
import math
p=0; f=0
def ck(n,c):
    global p,f
    if c: p+=1; print(f"PASS {n}")
    else: f+=1; print(f"FAIL {n} <-- НЕВЕРНО")

PHI=(1+5**0.5)/2                      # золотое ≈1.618

# ── заряженные лептоны (PDG, МэВ) ──
me,mm,mt = 0.51099895, 105.6583755, 1776.86
sq=[math.sqrt(x) for x in (me,mm,mt)]
Q=(me+mm+mt)/sum(sq)**2
ck(f"Койде Q(лептоны)=2/3 (●, σ½-грань РАНГА 3): {Q:.5f}", abs(Q-2/3)<2e-3)

# фаза Койде δ (азимут √m-вектора): c_k=(√m_k/среднее−1)/√2 ; τ — макс
mean=sum(sq)/3
cs=[(s/mean-1)/math.sqrt(2) for s in sq]
delta=math.acos(max(cs))             # ≈ фаза τ
ck(f"фаза Койде δ≈2/9 (◐, даёт ОБА отношения μ/e,τ/μ): δ={delta:.5f} vs 2/9={2/9:.5f}", abs(delta-2/9)<2e-3)
# контроль: эта (Q,δ) воспроизводит реальные отношения
ang=[delta+2*math.pi*k/3 for k in range(3)]
sm=sorted((1+math.sqrt(2)*math.cos(a))**2 for a in ang)
ck(f"(2/3,2/9) воспроизводит отношения: μ/e={sm[1]/sm[0]:.1f}(real 206.8), τ/μ={sm[2]/sm[1]:.2f}(real 16.82)",
   abs(sm[1]/sm[0]-206.8)<5 and abs(sm[2]/sm[1]-16.82)<0.3)

# ★ 2/9 — ЗОЛОТОЕ ли? сравниваем с золотыми кандидатами
gold_cand={"1/φ³":1/PHI**3,"2−φ":2-PHI,"1/φ²·":1/PHI**2-1/PHI**3}
best=min(abs(2/9-v) for v in gold_cand.values())
ck(f"★фаза 2/9 — НЕ золотая (ближайший золотой кандидат off {best/(2/9)*100:.1f}%>1%)", best/(2/9)>0.03)
ck("⟹ заряженные лептоны: Койде(р3)+фаза 2/9 — БЕЗ золота (φ≈1.618 не участвует)", True)

# ── φ-степенной тест отношений (золото даёт степени?) ──
e_mue=math.log(mm/me)/math.log(PHI); e_taumu=math.log(mt/mm)/math.log(PHI)
ck(f"масс-отношения ≠ степени φ: log_φ(μ/e)={e_mue:.2f}, log_φ(τ/μ)={e_taumu:.2f} — НЕ целые (фит)",
   abs(e_mue-round(e_mue))>0.05 and abs(e_taumu-round(e_taumu))>0.05)

# ── кварки: Койде НЕ 2/3 (лептон-специфично) ──
up=[2.16,1270,172690]; dn=[4.67,93.4,4180]
Qu=sum(up)/sum(math.sqrt(x) for x in up)**2; Qd=sum(dn)/sum(math.sqrt(x) for x in dn)**2
ck(f"кварки: Койде ≠ 2/3 (up={Qu:.3f}, down={Qd:.3f}) — лептон-специфично", abs(Qu-2/3)>0.05 and abs(Qd-2/3)>0.05)

# ── ГДЕ золото реально: НЕЙТРИННОЕ смешивание (A₅, tan θ₁₂=1/φ) — приближённо ──
sin2_gold=1/(1+PHI**2)               # tan θ=1/φ ⟹ sin²θ=1/(1+φ²)
sin2_meas=0.307
off=abs(sin2_gold-sin2_meas)/sin2_meas
ck(f"★золото→нейтрино: sin²θ₁₂(зол)={sin2_gold:.3f} vs изм {sin2_meas:.3f} — приближённо (off {off*100:.0f}%, ◐)",
   0.05<off<0.20)

# ── 2/9 vs Кабиббо λ (где 2/9 хоть близко) ──
lam=0.2265
ck(f"2/9 vs Кабиббо λ={lam}: близко но не точно (off {abs(2/9-lam)/lam*100:.1f}%); θ_W=2/9 ОПРОВЕРГНУТ (3/8=SU5)",
   abs(2/9-lam)/lam<0.03)

print()
verdict={
 "Койде Q=2/3 (угол масс) — РАНГ 3 (σ½-грань), не 5": "● solid",
 "фаза δ≈2/9 даёт отношения лептонов — но 2/9 НЕ золото, и НЕ выведена": "◐ узнавание (0.07% совпадение)",
 "★золото φ≈1.618 НЕ даёт иерархию заряж. лептонов": "✗ гипотеза не подтвердилась",
 "золото реально → НЕЙТРИННОЕ смешивание (A₅, tan θ₁₂=1/φ)": "◐ приближённо (~10% off), не массы",
 "кварки Койде≠2/3; масс-отношения ≠ степени φ": "● (фит, не золото)",
 "★стена ДЕРЖИТСЯ для значений масс; ранг 5=смешивание не иерархия": "○ числа за стеной",
}
for k,v in verdict.items(): print(f"  {k}: {v}")
print(f"\nИТОГ: {p} PASS / {f} FAIL")
