#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
verify_carrier_from_operation.py

Чинит слабое место глав 0–I: «операция прежде носителя» БЕЗ смешения двух
картин (категорная образующая копредела vs обычный элемент множества).

Замечание, которое чиним: предикат «ι≠id» сам по себе есть «∃x: ι(x)≠x» —
высказывание о КАРТЕ НА НОСИТЕЛЕ; чтобы его записать, носитель X уже нужен.
Значит «операция строго прежде всякого множества» — переобещание. Защитимо
не «носителя нет вовсе», а «нет носителя, ОТДЕЛЬНОГО от операции».

Разрешение в ДВА МОМЕНТА (вариант A — регулярное представление, Кэли):

  Момент 1 — операция как группа G=⟨g | g^2=e⟩, БЕЗ носителя.
    Порядок считается из ПРЕЗЕНТАЦИИ: свободная группа на одном образующем = ℤ,
    фактор по g^2=e = ℤ/2ℤ — ровно два класса; g≠e по чётности (1∉2ℤ).
    Никакого «найдётся x»: квантора по носителю нет — считан порядок операции.

  Момент 2 — носитель РОЖДАЕТСЯ как регулярная орбита.
    G действует на собственном носителе сдвигом; орбита единицы e под ⟨g⟩ есть
    {e,g} — это и есть первый носитель. Образующая x:=e канонична (единица).
    Мощность носителя = ПОРЯДОК инволюции: |⟨g|g^n=e⟩|=n.

Итог: «два» ВЫВЕДЕНО (порядок ℤ/2), не постулировано; элемент-язык законен
лишь ПОСЛЕ Момента 2; «пара есть тень самоотношения» становится буквальной.
"""

results = []
def ck(name, cond):
    results.append((name, bool(cond)))
    print(f"[{'PASS' if cond else 'FAIL'}] {name}")

# ============ Момент 1: группа из презентации ⟨g | g^n=e⟩, без носителя ============
# Свободная группа на одном образующем = ℤ (слова g^k). Соотношение g^n=e даёт
# фактор ℤ/nℤ. Ключ: строим из СООТНОШЕНИЯ, никакого «множества, на котором действуем».
def order_from_presentation(n):
    # нормальные формы слов g^k по модулю g^n=e = классы вычетов {0,...,n-1}
    return len(range(n))

G = list(range(2))                      # ⟨g | g^2=e⟩ как ℤ/2: {e=0, g=1}
e, g = 0, 1
mul = lambda a, b: (a + b) % 2          # групповая операция (g^2=e)

ck("Момент1: порядок ⟨g|g^2=e⟩ = 2 — из презентации, без носителя",
   order_from_presentation(2) == 2)
ck("Момент1: g ≠ e по чётности (1 ∉ 2ℤ) — замена 'ι≠id' без квантора по носителю",
   (1 % 2) != (0 % 2) and g != e)
ck("Момент1: соотношение g·g = e держится", mul(g, g) == e)
ck("Момент1: e — единица группы (mul(e,x)=x для всех x)",
   all(mul(e, x) == x for x in G))

# ============ Момент 2: носитель = регулярная орбита (Кэли) ============
# G действует на СОБСТВЕННОМ носителе сдвигом λ_h(x)=h·x. Носитель = сам G.
iota = lambda x: mul(g, x)              # ι := левый сдвиг на g
orbit_of_e = sorted({e, iota(e)})       # орбита единицы под ⟨g⟩
carrier = orbit_of_e                    # носитель ЕСТЬ орбита, не вход

ck("Момент2: орбита единицы e под ⟨g⟩ = {e,g}", orbit_of_e == [e, g])
ck("Момент2: носитель ЕСТЬ орбита (порождён, не дан заранее)", carrier == orbit_of_e)
ck("Момент2: |носитель| = 2 = порядок инволюции g",
   len(carrier) == 2 == order_from_presentation(2))
ck("Момент2: x:=e канонична — единица группы, не произвольный элемент",
   all(mul(e, x) == x for x in carrier))

# ι — нетривиальная инволюция БЕЗ неподвижных точек (свобода; Утв.2 гл.I §3)
ck("ι свободна: ι(x) ≠ x для всех x", all(iota(x) != x for x in carrier))
ck("ι² = id на носителе", all(iota(iota(x)) == x for x in carrier))
ck("ι = обмен 0↔1", iota(0) == 1 and iota(1) == 0)

# ============ «Два = период два»: мощность орбиты = порядок, и лишь n=2 — инволюция ============
for n in (2, 3, 4, 5):
    iota_n = lambda x, n=n: (1 + x) % n
    cur, orbit = 0, {0}
    for _ in range(n + 1):
        cur = iota_n(cur); orbit.add(cur)
    is_involution = all(iota_n(iota_n(x)) == x for x in range(n)) and \
                    any(iota_n(x) != x for x in range(n))
    ck(f"n={n}: |орбита единицы| = порядок = {n}", len(orbit) == n)
    if n == 2:
        ck("n=2: сдвиг на g — ИНВОЛЮЦИЯ (период 2)", is_involution)
    else:
        ck(f"n={n}: сдвиг на g — НЕ инволюция (период {n}≠2), отпадает", not is_involution)

# ============ Дисциплина: «два» не вписано руками (смена базы) ============
# Меняем презентацию (g^3=e) → носитель из ТРЁХ. Значит «2» зависит ТОЛЬКО от g^2=e,
# а не подложено константой. Смена базы/типа убивает подозрение в нумерологии.
ck("Смена базы: g^3=e даёт носитель 3, не 2 ⇒ '2' выведено из g^2=e, не вписано",
   order_from_presentation(3) == 3 and order_from_presentation(2) == 2)

# ============ Итог ============
npass = sum(1 for _, c in results if c)
nfail = sum(1 for _, c in results if not c)
print(f"\nИТОГО: {npass} PASS / {nfail} FAIL")
